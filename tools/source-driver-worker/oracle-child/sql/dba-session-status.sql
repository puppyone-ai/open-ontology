SET DEFINE ON
SET VERIFY OFF
SET FEEDBACK OFF
SET HEADING OFF
SET PAGESIZE 0
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER = FREEPDB1;
SELECT 'status|' || NVL(status, 'ABSENT') || '|' || NVL(SUBSTR(module, 1, 64), '-')
FROM v$session
WHERE sid = &1 AND serial# = &2;
PROMPT status|done
EXIT
