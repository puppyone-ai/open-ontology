-- Least privilege for the single reader. No ANY, no LOGMINING.
SET DEFINE OFF
SET FEEDBACK OFF
SET HEADING OFF
SET PAGESIZE 0
SET LINESIZE 200
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE

ALTER SESSION SET CONTAINER = FREEPDB1;

GRANT CREATE SESSION TO oo04_reader;
GRANT SELECT, FLASHBACK ON oo04_fix.t_batch TO oo04_reader;
GRANT SELECT, FLASHBACK ON oo04_fix.t_wide TO oo04_reader;
GRANT SELECT, FLASHBACK ON oo04_fix.t_ts TO oo04_reader;
-- EXECUTE on SYS.DBMS_FLASHBACK also covers TRANSACTION_BACKOUT.
-- The reader does not receive it. The DBA publishes the SCN.
BEGIN
  EXECUTE IMMEDIATE 'REVOKE EXECUTE ON sys.dbms_flashback FROM oo04_reader';
EXCEPTION
  WHEN OTHERS THEN
    IF SQLCODE NOT IN (-1927, -1951, -1952) THEN
      RAISE;
    END IF;
END;
/

BEGIN EXECUTE IMMEDIATE 'NOAUDIT POLICY oo_dl01w1_04_p2_acts';
EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP AUDIT POLICY oo_dl01w1_04_p2_acts';
EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE AUDIT POLICY oo_dl01w1_04_p2_acts ACTIONS ALL;
AUDIT POLICY oo_dl01w1_04_p2_acts BY oo04_reader;

PROMPT grants|done
EXIT
