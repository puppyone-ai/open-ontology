def child_main(args):
    fn = CANDIDATES[args.child][1]
    t0 = time.perf_counter()
    cpu0 = time.process_time()
    out = fn(Path(args.wav), args.models)
    out["wall_s"] = time.perf_counter() - t0
    out["cpu_s"] = time.process_time() - cpu0
    out["peak_rss_mb"] = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / (1024 * 1024 if sys.platform == "darwin" else 1024)
    print("RESULT " + json.dumps(out, ensure_ascii=False))


def run_candidate(name, wav, models, timeout=7200):
    env = dict(os.environ, OMP_NUM_THREADS="1", OPENBLAS_NUM_THREADS="1", HF_HUB_OFFLINE="1", PYANNOTE_METRICS_ENABLED="0")
    py = os.environ.get("OO_BAKEOFF_PY_" + name.upper().replace("-", "_").replace(".", "_"), sys.executable)
    p = subprocess.run([py, "-B", __file__, "--child", name, "--wav", str(wav), "--models", str(models)],
                       capture_output=True, text=True, timeout=timeout, env=env)
    for line in p.stdout.splitlines():
        if line.startswith("RESULT "):
            return json.loads(line[7:]), None
    return None, (p.stderr.strip().splitlines() or ["no output"])[-1][:200]


def score(truth, asr, diar, total_ms):
    ref_text = "".join(t["text"] for t in truth)
    rows = {}
    if asr:
        rows["cer"] = round(cer(ref_text, asr["text"]), 4)
    if diar:
        ref = [(t["speaker"], t["start_ms"], t["end_ms"]) for t in truth]
        rows["der"] = round(der(ref, diar["segments"], total_ms), 4)
    return rows


def render_report(rows, audio_s, notes):
    out = ["# ASR and speaker-separation bake-off (D72, B-S10-06)", "",
           f"Synthetic 3-person Chinese meeting, {audio_s:.0f} s of audio. {notes}", "",
           "| Candidate | Kind | CER | DER | CPU RTF | Peak RAM (MB) | License | Verdict |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        lic = LICENSES.get(r["lic_key"], ("", ""))
        out.append(f"| {r['name']} | {r['kind']} | {r.get('cer', '-')} | {r.get('der', '-')} | {r.get('rtf', '-')} | "
                   f"{r.get('rss', '-')} | {lic[0]} | {r.get('status') or lic[1]} |")
    return "\n".join(out) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--golden", default="testing/super-ontology/golden/media")
    ap.add_argument("--work", default="/tmp/oo-bakeoff")
    ap.add_argument("--models", default=os.environ.get("OO_BAKEOFF_MODELS", "/tmp/oo-bakeoff/models"))
    ap.add_argument("--tts", default=None, help="`say` (macOS voices) or the directory of the sherpa-onnx kokoro model; generates the meeting")
    ap.add_argument("--candidates", default=",".join(CANDIDATES))
    ap.add_argument("--report")
    ap.add_argument("--metrics-only", action="store_true")
    ap.add_argument("--child")
    ap.add_argument("--wav")
    a = ap.parse_args(argv)
    if a.child:
        return child_main(a)
    if a.metrics_only:
        assert abs(cer("你好，世界", "你好世界") ) == 0 and cer("你好世界", "你号世界") == 0.25
        ref = [("A", 0, 1000), ("B", 1000, 2000)]
        assert der(ref, [("x", 0, 1000), ("y", 1000, 2000)], 2000) == 0.0
        print("metrics ok")
        return 0
    work = Path(a.work)
    wav = work / "meeting-3spk.wav"
    truth_path = work / "meeting-3spk.truth.json"
    if not wav.exists():
        if a.tts == "say":
            synthesize_say(a.golden, work)
        elif a.tts:
            synthesize(a.golden, work, a.tts, {"A": 0, "B": 1, "C": 2})
        else:
            sys.exit("no meeting audio: pass --tts say (macOS) or --tts <kokoro dir> to generate it, or put meeting-3spk.wav and .truth.json in --work")
    truth = json.loads(truth_path.read_text())["turns"]
    with wave.open(str(wav), 'rb') as w:
        total_ms = int(w.getnframes() * 1000 / w.getframerate())
    rows = []
    for name in a.candidates.split(","):
        kind = CANDIDATES.get(name, ("?", None))[0]
        res, err = run_candidate(name, wav, a.models) if name in CANDIDATES else (None, "unknown candidate")
        row = {"name": name, "kind": kind, "lic_key": {"3dspeaker-clustering": "sherpa-onnx+3d-speaker"}.get(name, name)}
        if res is None:
            row["status"] = f"not run: {err}"
        elif "by_threshold" in res:
            ref = [(t["speaker"], t["start_ms"], t["end_ms"]) for t in truth]
            for th, d in res["by_threshold"].items():
                r = dict(row, name=f"{name} (distance {th}, {d['speakers']} speakers)")
                r["der"] = round(der(ref, d["segments"], total_ms), 4)
                r["rtf"] = round(rtf(res.get("infer_s", res["cpu_s"]), total_ms / 1000), 3)
                r["rss"] = round(res["peak_rss_mb"])
                rows.append(r)
            continue
        else:
            row.update(score(truth, res if kind == "asr" else None, res if kind == "diar" else None, total_ms))
            row["rtf"] = round(rtf(res.get("infer_s", res["cpu_s"]), total_ms / 1000), 3)
            row["rss"] = round(res["peak_rss_mb"])
        rows.append(row)
    text = render_report(rows, total_ms / 1000, "Measured on this host, one thread per candidate.")
    print(text)
    if a.report:
        Path(a.report).write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
