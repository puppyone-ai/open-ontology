# ---- metrics ----------------------------------------------------------------------------------------------------
def norm_text(s):
    s = unicodedata.normalize("NFKC", s).lower()
    return "".join(ch for ch in s if not unicodedata.category(ch).startswith(("P", "Z", "S", "C")))


def edit_distance(a, b):
    prev = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        cur = [i]
        for j, cb in enumerate(b, 1):
            cur.append(min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (ca != cb)))
        prev = cur
    return prev[-1]


def cer(ref, hyp):
    r, h = norm_text(ref), norm_text(hyp)
    return edit_distance(r, h) / max(1, len(r))


def der(ref, hyp, total_ms, frame_ms=10):
    """Diarization error rate. `ref`/`hyp`: [(speaker, start_ms, end_ms)] non-overlapping per list.

    DER = (missed speech + false alarm + speaker confusion) / reference speech, frame by frame, with the
    reference-to-hypothesis speaker mapping that minimises the error (brute force, at most 6 speakers).
    """
    n = total_ms // frame_ms + 1
    r = [-1] * n
    h = [-1] * n
    rs = sorted({s for s, _, _ in ref})
    hs = sorted({s for s, _, _ in hyp})
    for lab, segs, ids in ((r, ref, rs), (h, hyp, hs)):
        for s, a, b in segs:
            for i in range(a // frame_ms, min(n, b // frame_ms)):
                lab[i] = ids.index(s)
    ref_speech = sum(1 for v in r if v >= 0)
    if ref_speech == 0:
        return 0.0
    missed = sum(1 for x, y in zip(r, h) if x >= 0 and y < 0)
    false_alarm = sum(1 for x, y in zip(r, h) if x < 0 and y >= 0)
    # co-occurrence counts of (reference speaker, hypothesis speaker) on frames where both speak
    co = {}
    for x, y in zip(r, h):
        if x >= 0 and y >= 0:
            co[(x, y)] = co.get((x, y), 0) + 1
    both = sum(co.values())
    k = max(len(rs), len(hs))
    best_match = 0
    for perm in itertools.permutations(range(k), len(rs)):
        best_match = max(best_match, sum(co.get((i, perm[i]), 0) for i in range(len(rs))))
    return (missed + false_alarm + (both - best_match)) / ref_speech


def rtf(wall_s, audio_s):
    return wall_s / audio_s


# ---- ground truth and TTS ---------------------------------------------------------------------------------------
def load_script(golden):
    return json.loads((Path(golden) / "script.json").read_text(encoding="utf-8"))


def write_wav(path, x):
    import numpy as np

    pcm = (np.clip(x, -1, 1) * 32767).astype("<i2")
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())


def read_wav(path):
    import numpy as np

    with wave.open(str(path), "rb") as w:
        assert (w.getnchannels(), w.getframerate(), w.getsampwidth()) == (1, SR, 2)
        return np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float32) / 32768.0


def resample(x, sr_from, sr_to=SR):
    import numpy as np

    if sr_from == sr_to:
        return np.asarray(x, dtype=np.float32)
    n = int(round(len(x) * sr_to / sr_from))
    return np.interp(np.linspace(0, len(x) - 1, n), np.arange(len(x)), x).astype(np.float32)


# Chosen by CAM++ cosine similarity of the voices: Tingting is far from all others; Sandy and Rocko are the least similar pair
# of the rest (0.46 against 0.73 within a voice), so the three speakers are separable but not trivially so.
THRESHOLDS = (0.55, 0.45, 0.40, 0.35, 0.30, 0.25)
SAY_VOICES = {"A": "Tingting", "B": "Sandy (中文（中国大陆）)", "C": "Rocko (中文（中国大陆）)"}


def synthesize_say(golden, work):
    """Offline TTS with the macOS `say` voices (three different zh_CN voices) and ffmpeg for 16 kHz mono.

    The audio stays in `--work`: it is generated at bake-off time and never committed or shipped (Apple's voices are
    not ours to redistribute); the committed files are the script, this generator and the timing truth. Used where
    the Apache-2.0 Kokoro model of sherpa-onnx cannot be fetched (`synthesize`).
    """
    import numpy as np

    script = load_script(golden)
    out = Path(work)
    out.mkdir(parents=True, exist_ok=True)
    rnd = np.random.default_rng(20261117)
    parts, truth, t = [], [], 0
    lo, hi = script["pause_ms"]
    for i, (who, text) in enumerate(script["turns"]):
        aiff, wav = out / f"t{i}.aiff", out / f"t{i}.wav"
        subprocess.run(["say", "-v", SAY_VOICES[who], "-o", str(aiff), text], check=True)
        subprocess.run(["ffmpeg", "-nostdin", "-v", "error", "-y", "-i", str(aiff), "-ac", "1", "-ar", str(SR), str(wav)], check=True)
        x = read_wav(wav)
        x = x / max(1e-6, float(np.max(np.abs(x)))) * 0.7
        pause = int(rnd.integers(lo, hi + 1))
        parts += [x, np.zeros(pause * SR // 1000, dtype=np.float32)]
        truth.append({"speaker": who, "text": text, "start_ms": t, "end_ms": t + len(x) * 1000 // SR})
        t += len(x) * 1000 // SR + pause
        aiff.unlink()
        wav.unlink()
    audio = np.concatenate(parts)
    audio = audio + rnd.normal(0, 0.002, audio.shape).astype(np.float32)
    write_wav(out / "meeting-3spk.wav", audio)
    (out / "meeting-3spk.truth.json").write_text(json.dumps({"tts": "macos-say", "voices": SAY_VOICES, "turns": truth}, ensure_ascii=False, indent=1))
    return out / "meeting-3spk.wav", truth


def synthesize(golden, work, tts_dir, speaker_ids):
    """Generate the meeting with sherpa-onnx's offline Kokoro (Apache-2.0). `speaker_ids`: {"A": sid, ...}."""
    import numpy as np
    import sherpa_onnx

    script = load_script(golden)
    d = Path(tts_dir)
    cfg = sherpa_onnx.OfflineTtsConfig(model=sherpa_onnx.OfflineTtsModelConfig(
        kokoro=sherpa_onnx.OfflineTtsKokoroModelConfig(
            model=str(d / "model.onnx"), voices=str(d / "voices.bin"), tokens=str(d / "tokens.txt"),
            data_dir=str(d / "espeak-ng-data"), dict_dir=str(d / "dict"), lexicon=",".join(str(p) for p in sorted(d.glob("lexicon*.txt")))),
        num_threads=2, provider="cpu"))
    tts = sherpa_onnx.OfflineTts(cfg)
    rnd = np.random.default_rng(20261117)
    parts, truth, t = [], [], 0
    lo, hi = script["pause_ms"]
    for who, text in script["turns"]:
        audio = tts.generate(text, sid=speaker_ids[who], speed=1.0)
        x = resample(np.asarray(audio.samples, dtype=np.float32), audio.sample_rate)
        x = x / max(1e-6, float(np.max(np.abs(x)))) * 0.7
        pause = int(rnd.integers(lo, hi + 1))
        parts += [x, np.zeros(pause * SR // 1000, dtype=np.float32)]
        truth.append({"speaker": who, "text": text, "start_ms": t, "end_ms": t + len(x) * 1000 // SR})
        t += len(x) * 1000 // SR + pause
    audio = np.concatenate(parts)
    audio = audio + rnd.normal(0, 0.002, audio.shape).astype(np.float32)  # a little room noise
    out = Path(work)
    out.mkdir(parents=True, exist_ok=True)
    write_wav(out / "meeting-3spk.wav", audio)
    (out / "meeting-3spk.truth.json").write_text(json.dumps({"speaker_ids": speaker_ids, "turns": truth}, ensure_ascii=False, indent=1))
    return out / "meeting-3spk.wav", truth


# ---- candidates (run in a child process so RAM and time are per candidate) --------------------------------------
def ms_dir(models, name):
    return Path(models) / "ms" / "models" / name / "snapshots" / "master"


def run_paraformer(wav, models):
    """FunASR paraformer-zh (Apache-2.0 weights) with fsmn-vad, torch CPU, one thread, no punctuation model."""
    import torch
    from funasr import AutoModel

    torch.set_num_threads(1)
    m = AutoModel(model=str(ms_dir(models, "iic--speech_paraformer-large-vad-punc_asr_nat-zh-cn-16k-common-vocab8404-pytorch")),
                  vad_model=str(ms_dir(models, "iic--speech_fsmn_vad_zh-cn-16k-common-pytorch")), punc_model=None,
                  device="cpu", disable_update=True, disable_pbar=True, ncpu=1)
    t0 = time.process_time()
    res = m.generate(input=str(wav), batch_size_s=60)
    text = "".join(r.get("text", "") for r in res)
    return {"text": text, "infer_s": time.process_time() - t0}


def run_paraformer_onnx(wav, models):
    """The same Paraformer-zh as a quantized ONNX export (funasr-onnx, MIT; weights Apache-2.0), onnxruntime, no torch.
    This is the shipped path: chunks of at most 25 s from the pipeline's VAD chunker."""
    import tempfile

    import numpy as np
    from funasr_onnx import Paraformer

    d = ms_dir(models, "iic--speech_paraformer-large_asr_nat-zh-cn-16k-common-vocab8404-onnx")
    m = Paraformer(str(d), batch_size=1, quantize=True, intra_op_num_threads=1)
    x = read_wav(wav)
    here = Path(__file__).resolve().parents[2] / "tools" / "media-parser"
    sys.path.insert(0, str(here))
    from asr import chunks as ck

    frame = 512
    probs = [float(np.sqrt(np.mean(x[i * frame:(i + 1) * frame] ** 2)) > 0.01) for i in range(len(x) // frame)]
    # The quantized export loses accuracy on long inputs: chunks of at most 12 s (measured: 25 s gave CER 0.35).
    chunks = ck.make_chunks(ck.speech_segments(probs, total_ms=len(x) * 1000 // SR, min_silence_ms=150), probs, max_ms=12_000)
    text = ""
    t0 = time.process_time()
    with tempfile.TemporaryDirectory() as tmp:
        for i, (s_ms, e_ms) in enumerate(chunks):
            f = Path(tmp) / f"c{i}.wav"
            write_wav(f, x[s_ms * SR // 1000:e_ms * SR // 1000])
            text += m([str(f)])[0]["preds"][0]
    return {"text": text, "chunks": len(chunks), "infer_s": time.process_time() - t0}


def run_qwen3_asr_bf16(wav, models):
    return run_qwen3_asr(wav, models, dtype="bfloat16")


def run_qwen3_asr(wav, models, dtype="float32"):
    """Qwen3-ASR-0.6B, weights Apache-2.0. MEASUREMENT ONLY: this runner uses the `qwen-asr` package because the stock
    transformers 5.23 cannot load the released checkpoint (key layout and config differ). That package pulls GPL-3.0
    soynlp and must never be in a shipped image (D64); the shipped path would be our own loader. Chunks of at most 25 s
    cut at silence (the pipeline's VAD chunker), greedy decoding."""
    import numpy as np
    import torch
    from qwen_asr import Qwen3ASRModel

    torch.set_num_threads(1)
    m = Qwen3ASRModel.from_pretrained(str(ms_dir(models, "Qwen--Qwen3-ASR-0.6B")), dtype=getattr(torch, dtype), device_map="cpu",
                                      max_inference_batch_size=1, max_new_tokens=256)
    x = read_wav(wav)
    here = Path(__file__).resolve().parents[2] / "tools" / "media-parser"
    sys.path.insert(0, str(here))
    from asr import chunks as ck

    frame = 512
    probs = [float(np.sqrt(np.mean(x[i * frame:(i + 1) * frame] ** 2)) > 0.01) for i in range(len(x) // frame)]
    chunks = ck.make_chunks(ck.speech_segments(probs, frame_ms=32, total_ms=len(x) * 1000 // SR), probs, max_ms=25_000)
    text = ""
    t0 = time.process_time()
    for s_ms, e_ms in chunks:
        r = m.transcribe(audio=(x[s_ms * SR // 1000:e_ms * SR // 1000], SR), language="Chinese")
        text += r[0].text
    return {"text": text, "chunks": len(chunks), "infer_s": time.process_time() - t0}


def run_diarization_3dspeaker(wav, models):
    """3D-Speaker CAM++ (Apache-2.0) window embeddings, energy VAD, our window clustering (tools/media-parser/asr)."""
    import numpy as np
    import torch
    from modelscope.pipelines import pipeline
    from modelscope.utils.constant import Tasks

    torch.set_num_threads(1)
    here = Path(__file__).resolve().parents[2] / "tools" / "media-parser"
    sys.path.insert(0, str(here))
    from asr import chunks as ck
    from asr import diarize as dz

    sv = pipeline(task=Tasks.speaker_verification, model=str(ms_dir(models, "iic--speech_campplus_sv_zh-cn_16k-common")))
    x = read_wav(wav)
    frame = 512
    probs = [float(np.sqrt(np.mean(x[i * frame:(i + 1) * frame] ** 2)) > 0.01) for i in range(len(x) // frame)]
    chunks = ck.make_chunks(ck.speech_segments(probs, total_ms=len(x) * 1000 // SR), probs)
    spans, vecs = [], []
    t0 = time.process_time()
    for s_ms, e_ms in chunks:
        wins = dz.windows_for(s_ms, e_ms)
        if not wins:
            continue
        audio = [x[a * SR // 1000:b * SR // 1000] for a, b in wins]
        embs = sv(audio + [audio[0]], output_emb=True)["embs"][:len(audio)]
        vecs += [np.asarray(e, dtype=np.float32) for e in embs]
        spans += wins
    by = {}
    for th in THRESHOLDS:
        labels = dz.relabel_by_first_appearance(dz.cluster(np.stack(vecs), th, None), [a for a, _ in spans])
        # each window votes for its middle half so the turns tile; merge neighbours of the same speaker
        segs = []
        for (a, b), lab in zip(spans, labels):
            a2, b2 = a + (b - a) // 4, b - (b - a) // 4
            if segs and segs[-1][0] == lab and a2 - segs[-1][2] <= 100:
                segs[-1] = (lab, segs[-1][1], b2)
            else:
                segs.append((lab, a2, b2))
        by[str(th)] = {"segments": segs, "speakers": len(set(labels))}
    return {"by_threshold": by, "windows": len(spans), "infer_s": time.process_time() - t0}


