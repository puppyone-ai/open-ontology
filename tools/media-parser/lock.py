#!/usr/bin/env python3
"""Regenerate requirements.lock for media-parser (B-S10-05).

    python3 -B tools/media-parser/lock.py [--exclude-newer 2026-11-10T10:29:30Z]

Resolves requirements.in with uv for CPython 3.13 on linux aarch64 and x86_64
(no torch; the OpenCV wheels are dropped, see requirements.in),
requires the same package set on both, and writes one lock whose hashes are the
union of both architectures, usable with `pip install --require-hashes`. The
7-day age floor is the supply-chain policy (section 4).
"""
import re
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
DROP = ("opencv-contrib-python", "opencv-python", "opencv-python-headless", "opencv-contrib-python-headless")
PLATFORMS = ["aarch64-unknown-linux-gnu", "x86_64-unknown-linux-gnu"]


def resolve(platform, newer):
    with tempfile.NamedTemporaryFile("r", suffix=".txt") as out:
        subprocess.run(
            ["uv", "pip", "compile", str(HERE / "requirements.in"), "--python-version", "3.13",
             "--python-platform", platform, "--generate-hashes", "--exclude-newer", newer,
             "--index-strategy", "unsafe-best-match", "--no-header", "-o", out.name],
            check=True, stdout=subprocess.DEVNULL)
        return parse(Path(out.name).read_text())


def parse(text):
    pkgs = {}
    for m in re.finditer(r"^(\S+==\S+) \\\n((?:    --hash=\S+(?: \\)?\n)+)((?:    #.*\n)*)", text, re.M):
        hashes = set(re.findall(r"sha256:[0-9a-f]{64}", m.group(2)))
        via = [ln.strip() for ln in m.group(3).splitlines()]
        pkgs[m.group(1)] = (hashes, via)
    return pkgs


def main():
    newer = "2026-11-10T10:29:30Z"
    if "--exclude-newer" in sys.argv:
        newer = sys.argv[sys.argv.index("--exclude-newer") + 1]
    per = [{k: v for k, v in resolve(p, newer).items() if not k.startswith(DROP)} for p in PLATFORMS]
    if set(per[0]) != set(per[1]):
        sys.exit(f"package sets differ: {sorted(set(per[0]) ^ set(per[1]))}")
    lines = [f"# generated by tools/media-parser/lock.py, exclude-newer {newer}, cp313, linux aarch64+x86_64",
             "# install: pip install --require-hashes --no-deps -r requirements.lock"]
    for name in sorted(per[0]):
        hashes = sorted(per[0][name][0] | per[1][name][0])
        lines.append(f"{name} \\")
        lines.append(" \\\n".join(f"    --hash={h}" for h in hashes))
        lines += [f"    {v}" for v in per[0][name][1]]
    (HERE / "requirements.lock").write_text("\n".join(lines) + "\n")
    print(f"{len(per[0])} packages")


if __name__ == "__main__":
    main()
