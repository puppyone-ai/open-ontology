#!/usr/bin/env python3
"""Regenerate campplus-export.lock (SO-F-S23-31): the hashed builder environment of the `campplus` Dockerfile stage.

    python3 -B tools/media-parser/campplus_lock.py [--exclude-newer 2026-11-10T10:29:30Z]

Same method and age floor as tools/doc-parser/lock.py: resolved with uv for CPython 3.13 on linux aarch64 and x86_64
(CPU-only torch from the PyTorch CPU index), the same package set on both, hashes are the union of both architectures.
"""
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "doc-parser"))
from lock import PLATFORMS, parse  # noqa: E402


def resolve(platform, newer):
    with tempfile.NamedTemporaryFile("r", suffix=".txt") as out:
        subprocess.run(
            ["uv", "pip", "compile", "campplus-export.in", "--python-version", "3.13",
             "--python-platform", platform, "--generate-hashes", "--exclude-newer", newer,
             "--extra-index-url", "https://download.pytorch.org/whl/cpu",
             "--index-strategy", "unsafe-best-match", "--no-header", "-o", out.name],
            check=True, stdout=subprocess.DEVNULL, cwd=HERE)
        return parse(Path(out.name).read_text())


def main():
    newer = "2026-11-10T10:29:30Z"
    if "--exclude-newer" in sys.argv:
        newer = sys.argv[sys.argv.index("--exclude-newer") + 1]
    per = [resolve(p, newer) for p in PLATFORMS]
    if set(per[0]) != set(per[1]):
        sys.exit(f"package sets differ: {sorted(set(per[0]) ^ set(per[1]))}")
    lines = [f"# generated by tools/media-parser/campplus_lock.py, exclude-newer {newer}, cp313, linux aarch64+x86_64",
             "# install: pip install --require-hashes --no-deps -r campplus-export.lock"]
    for name in sorted(per[0]):
        hashes = sorted(per[0][name][0] | per[1][name][0])
        lines.append(f"{name} \\")
        lines.append(" \\\n".join(f"    --hash={h}" for h in hashes))
        lines += [f"    {v}" for v in per[0][name][1]]
    (HERE / "campplus-export.lock").write_text("\n".join(lines) + "\n")
    print(f"{len(per[0])} packages")


if __name__ == "__main__":
    main()
