#!/usr/bin/env python3
"""Write the ClickHouse capture-binding plan for one private target.

The registry and the manifests carry paths and digests. They do not carry
admission authority: no binary path, no registry digest, and no admitted flag.
Hashes are checked against the attempt-06 files before anything is written.
"""

from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
from pathlib import Path


REPORT_SHA = "66a3386bd1f680d40713b8da220400f162735d2911a77f7fa91b36263bfe5234"
CONFIG_SHA = "b1c1fa84234d2cc33fd4d8da9d353bb498e6096557d53e439e32b589a7f7fbc1"
CAPTURE_SHA = "a9c9f0cd90ac73542652e507df4b50550a8ae24efcac9cb7c3180d8638d5b71c"
RECEIPT_SHA = "65b7f22fe26686f8a1e61d705a78d5a1a69f2a123de0b9dfce827cce2ffb59ef"
DECISION_SHA = "aedc6b434c4c5f2c9f2a4c4dd96258e4fd6dbdaeb2587da046dedc85add1ece7"
ARROW_SHA = "3e32e4f95456b2285bdaf9aa2988578635d97cabe5e83d07319c574f272fcf8b"
CONFIG_DIGEST = "435ac4a5d24920afab3343cb9de50a7e71d53ad107b35205cd686b596ea3b64a"
TYPE_DIGEST = "b935b6a9eb5f3384060ddaae7c588b6718933b644c0b8814d7deb467fe39bbb1"
INPUT_DIGEST = "007be53b723c87abb6594871ae082fe14d67c5b01aa192ff26c2c2c6371865cd"
STRING_SOURCES = {
    "note": "nullable_string",
    "code": "low_cardinality_string",
    "code_or_null": "low_cardinality_nullable_string",
    "label": "string",
}
SNAPSHOT = "oo-dl01w1-40-arrow-final"
DRIVER = "8b88485c0940e298a8edad500731f0a7688c61a135a943b217f9597e191c7f93"

ARROW_TOKENS = {
    "UInt64": ("uint64", 64, None),
    "Int64": ("int64", 64, None),
    "Decimal256(76, 10)": ("decimal256", 76, 10),
    "Binary": ("binary", None, None),
    "Dictionary(Int32, Binary)": ("dictionary_binary", None, None),
    'Timestamp(ns, "UTC")': ("timestamp_nanos_utc", None, None),
    "List(non-null Int64)": ("list_int64", None, None),
    "List(Binary)": ("list_binary", None, None),
}


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    digest.update(path.read_bytes())
    return digest.hexdigest()


def require(path: Path, expect: str) -> None:
    actual = sha256(path)
    if actual != expect:
        raise SystemExit(f"digest mismatch for {path}: {actual}")


def schema_preimage(catalog: dict) -> str:
    table = catalog["tables"][0]
    lines = [f"{table['logical_schema']}.{table['logical_table']}\n"]
    for column in table["columns"]:
        caveat = column.get("caveat") or ""
        lines.append(f"{column['logical_name']}\t{column['oid']}\t{column['typmod']}\t{caveat}\n")
    return "".join(lines)


def load_catalog_writer():
    path = Path(__file__).with_name("run_product.py")
    spec = importlib.util.spec_from_file_location("clickhouse_run_product", path)
    if spec is None or spec.loader is None:
        raise SystemExit("catalog writer is missing")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def require_catalog(path: Path) -> tuple[dict, str]:
    raw = path.read_bytes()
    writer = load_catalog_writer()
    expected = json.dumps(writer.catalog(writer.faithful_columns(), 3), indent=2) + "\n"
    if raw.decode("utf-8") != expected:
        raise SystemExit("catalog file is not the generated bytea binding")
    catalog = json.loads(raw)
    found = {}
    for column in catalog["tables"][0]["columns"]:
        name = column["logical_name"]
        if name not in STRING_SOURCES:
            continue
        if column["oid"] != 17 or column["typmod"] != -1 or column.get("caveat") is not None:
            raise SystemExit(f"{name} is not oid 17 bytea with the source type and an empty caveat")
        found[name] = column["source_type"]
    if found != STRING_SOURCES:
        raise SystemExit("string source types do not match the captured ClickHouse types")
    digest = sha256_text(schema_preimage(catalog))
    if catalog.get("schema_digest") != digest:
        raise SystemExit("schema digest does not match the oid preimage")
    return catalog, hashlib.sha256(raw).hexdigest()


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def columns_from_capture(capture: dict) -> list[dict]:
    fields = capture.get("field_types")
    if not isinstance(fields, list) or len(fields) != 12:
        raise SystemExit("capture field list is not the 12-field attempt-06 stream")
    columns = []
    for field in fields:
        token = ARROW_TOKENS.get(field.get("data_type"))
        if token is None:
            raise SystemExit(f"unsupported capture type {field.get('data_type')}")
        arrow_type, precision, scale = token
        column = {
            "arrow_type": arrow_type,
            "logical_name": field["name"],
            "name": field["name"],
            "nullable": field["nullable"],
        }
        if precision is not None:
            column["precision"] = precision
        if scale is not None:
            column["scale"] = scale
        columns.append(column)
    return columns


def registry_field(column: dict) -> dict:
    field = {
        "arrow_type": column["arrow_type"],
        "name": column["name"],
        "nullable": column["nullable"],
    }
    if "precision" in column:
        field["precision"] = column["precision"]
    if "scale" in column:
        field["scale"] = column["scale"]
    if column["arrow_type"] == "timestamp_nanos_utc":
        field["timezone"] = "UTC"
    return field


def manifest(columns: list[dict], owner: str, paths: argparse.Namespace, schema_digest: str) -> dict:
    return {
        "admission": {
            "decision_path": paths.decision_container,
            "receipt_path": paths.receipt_container,
        },
        "catalog_identity": {
            "config_digest": CONFIG_DIGEST,
            "input_digest": INPUT_DIGEST,
            "schema_digest": schema_digest,
            "type_digest": TYPE_DIGEST,
        },
        "protocol": "oo.pipeline.native-arrow-import/v1",
        "snapshot": {"kind": "token", "value": SNAPSHOT},
        "source_engine": "clickhouse",
        "source_generation": 1,
        "source_id": "clickhouse_268",
        "tables": [
            {
                "arrow_path": paths.arrow_container,
                "batch_sha256": ARROW_SHA,
                "columns": columns,
                "logical_schema": "readings",
                "logical_table": "final",
                "row_count": 3,
            }
        ],
        "target": {
            "ca_file": paths.ca_container,
            "database": "previewdb",
            "host": paths.host,
            "owner": owner,
            "password_file": paths.password_container,
            "port": 5432,
            "runtime_principal": "oo_admin",
            "shard": "clickhouse_268",
        },
        "target_storage": "postgresql",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--catalog", type=Path, required=True)
    parser.add_argument("--capture", type=Path, required=True)
    parser.add_argument("--receipt", type=Path, required=True)
    parser.add_argument("--decision", type=Path, required=True)
    parser.add_argument("--arrow", type=Path, required=True)
    parser.add_argument("--query-log", type=Path, required=True)
    parser.add_argument("--owner", required=True)
    parser.add_argument("--host", required=True)
    parser.add_argument("--report-container", required=True)
    parser.add_argument("--config-container", required=True)
    parser.add_argument("--catalog-container", required=True)
    parser.add_argument("--capture-container", required=True)
    parser.add_argument("--receipt-container", required=True)
    parser.add_argument("--decision-container", required=True)
    parser.add_argument("--arrow-container", required=True)
    parser.add_argument("--ca-container", required=True)
    parser.add_argument("--password-container", required=True)
    parser.add_argument("--registry-out", type=Path, required=True)
    parser.add_argument("--positive-out", type=Path, required=True)
    parser.add_argument("--negative-out", type=Path, required=True)
    args = parser.parse_args()

    require(args.report, REPORT_SHA)
    require(args.config, CONFIG_SHA)
    catalog, catalog_sha = require_catalog(args.catalog)
    require(args.capture, CAPTURE_SHA)
    require(args.receipt, RECEIPT_SHA)
    require(args.decision, DECISION_SHA)
    require(args.arrow, ARROW_SHA)
    query_log = json.loads(args.query_log.read_text())
    if query_log.get("query_id") != SNAPSHOT:
        raise SystemExit("snapshot token is not the attempt-06 query id")
    if catalog.get("engine") != "clickhouse" or catalog.get("source_id") != "clickhouse_268":
        raise SystemExit("catalog identity is not the ClickHouse sealed catalog")
    for name, expect in (
        ("config_digest", CONFIG_DIGEST),
        ("type_digest", TYPE_DIGEST),
        ("input_digest", INPUT_DIGEST),
    ):
        if catalog.get(name) != expect:
            raise SystemExit(f"catalog {name} changed")
    capture = json.loads(args.capture.read_text())
    columns = columns_from_capture(capture)
    binding = {
        "admission_receipt_path": args.receipt_container,
        "capture_receipt_path": args.capture_container,
        "capture_receipt_sha256": CAPTURE_SHA,
        "catalog_path": args.catalog_container,
        "catalog_sha256": catalog_sha,
        "config_digest": CONFIG_DIGEST,
        "config_path": args.config_container,
        "config_sha256": CONFIG_SHA,
        "decision_sha256": DECISION_SHA,
        "driver_digest": DRIVER,
        "driver_kind": "native-http",
        "driver_name": "ch-reader",
        "driver_version": "0.1.0",
        "fields": [registry_field(column) for column in columns],
        "input_digest": INPUT_DIGEST,
        "objects": [
            {
                "arrow_sha256": ARROW_SHA,
                "logical_schema": "readings",
                "logical_table": "final",
                "row_count": 3,
            }
        ],
        "protocol": "oo.source-admission.capture-binding/v1",
        "report_path": args.report_container,
        "report_sha256": REPORT_SHA,
        "schema_digest": catalog["schema_digest"],
        "snapshot": {"kind": "token", "value": SNAPSHOT},
        "source_engine": "clickhouse",
        "source_generation": 1,
        "source_id": "clickhouse_268",
        "type_digest": TYPE_DIGEST,
    }
    registry = {
        "bindings": [binding],
        "protocol": "oo.source-admission.binding-registry/v1",
    }
    positive = manifest(columns, args.owner, args, catalog["schema_digest"])
    negative = manifest(columns, "not-a-uuid", args, catalog["schema_digest"])
    rendered = json.dumps(registry)
    if "secret://" in rendered or "secret://" in json.dumps(positive):
        raise SystemExit("plan copied a secret reference")
    for key in ("admitted", "admission_bin", "registry_path", "registry_sha256", "approval"):
        if key in positive or key in positive["admission"]:
            raise SystemExit("manifest grants authority")
    args.registry_out.write_text(json.dumps(registry, indent=2) + "\n")
    args.positive_out.write_text(json.dumps(positive, indent=2) + "\n")
    args.negative_out.write_text(json.dumps(negative, indent=2) + "\n")
    print(hashlib.sha256(args.registry_out.read_bytes()).hexdigest())


if __name__ == "__main__":
    main()
