"""Fail-closed reader audit and CDC object attribution for a quiescent window."""
import json
import re
import time
import base64
from datetime import datetime
import xml.etree.ElementTree as ET

import runner
from sqlserver_acceptance import fingerprint, projections, source_rows


def classify(statement):
    statement = statement.strip()
    if statement in ("SET TRANSACTION ISOLATION LEVEL SNAPSHOT; BEGIN TRANSACTION",
                     "ROLLBACK TRANSACTION"):
        return "snapshot_session"
    # Strip quoted values/identifiers before scanning executable tokens.
    code = re.sub(r"N?'(?:''|[^'])*'|\[(?:\]\]|[^\]])*\]", " identifier ", statement)
    if not code.upper().startswith("SELECT "):
        raise ValueError("non-read top-level statement")
    if re.search(r"\b(INTO|INSERT|UPDATE|DELETE|MERGE|CREATE|ALTER|DROP|EXEC|EXECUTE|"
                 r"GRANT|REVOKE|DENY|TRUNCATE|BACKUP|RESTORE|DBCC|OPENROWSET|OPENQUERY|OPENDATASOURCE)\b",
                 code, re.I) or "--" in code or "/*" in code:
        raise ValueError("write or unattributed statement")
    if re.search(r"\bNEXT\s+VALUE\s+FOR\b", code, re.I):
        raise ValueError("sequence mutation")
    calls = re.findall(r"\b([A-Za-z_]\w*)\.(\[[^\]]+\]|[A-Za-z_]\w*)\s*\(",
                       re.sub(r"N?'(?:''|[^'])*'", " literal ", statement))
    for schema, function in calls:
        function = function.strip("[]")
        if not (schema.lower() == "sys" and function.lower() in (
                "fn_cdc_get_min_lsn", "fn_cdc_get_max_lsn", "fn_cdc_increment_lsn")
                or schema.lower() == "cdc" and function.lower().startswith("fn_cdc_get_all_changes_")):
            raise ValueError("unapproved qualified function")
    # Source queries are generated by the reviewed reader, not arbitrary SQL.
    return "select"


def business_state(run):
    result = {}
    for table in run.tables:
        left, _ = projections(run, table)
        chunks = []
        for lo in range(1, run.args.scale + 1, 10000) if table == "events" else [None]:
            where = "" if lo is None else f"WHERE id>={lo} AND id<{lo+10000}"
            chunks.append(fingerprint(source_rows(run, table, left, where)))
        result[table] = chunks
    return result


def cdc_state(run):
    objects = run.json_query(
        "SELECT s.name AS schema_name,t.name,t.object_id,t.is_ms_shipped FROM sys.tables t "
        "JOIN sys.schemas s ON s.schema_id=t.schema_id WHERE s.name='cdc' ORDER BY t.name")
    captures = run.json_query("SELECT capture_instance FROM cdc.change_tables")
    allowed = {"change_tables", "captured_columns", "index_columns", "ddl_history", "lsn_time_mapping"}
    allowed.update(c["capture_instance"] + "_CT" for c in captures)
    state = {}
    for obj in objects:
        name = obj["name"]
        if name not in allowed or not re.fullmatch(r"[A-Za-z0-9_]+", name):
            raise ValueError("unattributed CDC object")
        # sqlcmd emits no cell for an empty top-level FOR JSON result. A scalar
        # wrapper makes an empty table an explicit value, not missing evidence.
        wrapper = run.json_query(
            f"SELECT COALESCE((SELECT * FROM cdc.[{name}] "
            "FOR JSON PATH,INCLUDE_NULL_VALUES),'[]') AS payload")
        raw = wrapper[0]["payload"]
        raw = json.loads(raw) if isinstance(raw, str) else raw
        if not isinstance(raw, list):
            raise ValueError("CDC object JSON shape")
        # Metadata values can contain exact decimals; keep their decimal text.
        normalized = json.loads(json.dumps(raw, default=str))
        state[name] = {"catalog": obj, "classification": "SQL Server CDC-owned metadata or capture table",
                       "fingerprint": fingerprint(normalized), "rows": normalized}
    return state


def attribute_cdc(before, after, started, ended, scans_before, scans_after):
    """D12: allow only native idle-scan mapping appends, not arbitrary CDC writes."""
    if set(before) != set(after):
        raise ValueError("CDC inventory changed")
    count = 0
    for name, old in before.items():
        new = after[name]
        if old == new:
            continue
        if (name != "lsn_time_mapping" or old["catalog"] != new["catalog"]
                or not old["catalog"]["is_ms_shipped"]):
            raise ValueError("unattributed CDC object change")
        def lsn(row):
            value = base64.b64decode(row["start_lsn"], validate=True)
            if len(value) != 10:
                raise ValueError("CDC mapping LSN shape")
            return value
        old_rows = {lsn(row): row for row in old["rows"]}
        new_rows = {lsn(row): row for row in new["rows"]}
        if not old_rows or len(old_rows) != len(old["rows"]) or len(new_rows) != len(new["rows"]):
            raise ValueError("CDC mapping baseline or duplicate")
        if any(new_rows.get(key) != row for key, row in old_rows.items()):
            raise ValueError("CDC mapping removal or update")
        for key in new_rows.keys() - old_rows.keys():
            row = new_rows[key]
            if set(row) != {"start_lsn", "tran_begin_time", "tran_end_time", "tran_id", "tran_begin_lsn"}:
                raise ValueError("unknown CDC mapping columns")
            transaction = base64.b64decode(row["tran_id"], validate=True)
            begin = base64.b64decode(row["tran_begin_lsn"], validate=True)
            stamp = datetime.fromisoformat(row["tran_end_time"])
            if (key <= max(old_rows) or not transaction or len(transaction) > 6
                    or any(transaction) or begin != bytes(10)
                    or row["tran_begin_time"] != row["tran_end_time"]
                    or not datetime.fromisoformat(started) <= stamp <= datetime.fromisoformat(ended)):
                raise ValueError("not a CDC idle-scan mapping append")
            count += 1
    if count and (scans_after["empty_scans"] - scans_before["empty_scans"] < count
                  or scans_before["errors"] or scans_after["errors"]):
        raise ValueError("CDC scan telemetry does not attribute mapping append")
    return {"cdc_idle_scan_mapping_append": count}


def audit(run, command):
    rights = run.json_query(
        "SELECT HAS_PERMS_BY_NAME('dbo.growth_events','OBJECT','INSERT') AS ins,"
        "HAS_PERMS_BY_NAME('dbo.growth_events','OBJECT','UPDATE') AS upd,"
        "HAS_PERMS_BY_NAME('dbo.growth_events','OBJECT','DELETE') AS del,"
        "HAS_PERMS_BY_NAME(DB_NAME(),'DATABASE','CREATE TABLE') AS ddl,"
        "HAS_PERMS_BY_NAME(DB_NAME(),'DATABASE','CONTROL') AS control", admin=False)
    if rights != [{"ins": 0, "upd": 0, "del": 0, "ddl": 0, "control": 0}]:
        raise ValueError("reader is not read-only")
    inventory = (
        "SELECT s.name AS schema_name,o.name,o.type,o.object_id,CONVERT(nvarchar(40),o.modify_date,126) AS modified "
        "FROM sys.objects o JOIN sys.schemas s ON s.schema_id=o.schema_id "
        "WHERE s.name NOT IN ('sys','cdc') ORDER BY s.name,o.name,o.type")
    objects_before = run.json_query(inventory)
    jobs = run.json_query(
        "SELECT CONVERT(nvarchar(36),j.job_id) AS id,j.job_type,sj.name,sj.enabled "
        "FROM msdb.dbo.cdc_jobs j JOIN msdb.dbo.sysjobs sj ON sj.job_id=j.job_id "
        "WHERE j.database_id=DB_ID() AND j.job_type='capture'")
    if len(jobs) != 1 or jobs[0]["enabled"] != 1:
        raise ValueError("CDC capture job identity unavailable")
    # Aggregate session 0 does not expose the current scan's empty counter.
    # Retained individual sessions provide the actual observed idle scans.
    telemetry = ("SELECT COALESCE(SUM(CONVERT(bigint,empty_scan_count)),0) AS empty_scans,"
                 "COALESCE(SUM(CONVERT(bigint,error_count)),0) AS errors "
                 "FROM sys.dm_cdc_log_scan_sessions WHERE session_id>0")
    scans_before = run.json_query(telemetry)[0]
    started = run.json_query("SELECT CONVERT(nvarchar(40),GETDATE(),126) AS stamp")[0]["stamp"]
    # Fixture admin configures audit; product principal never creates objects.
    run.sql("CREATE EVENT SESSION oo_readonly ON SERVER "
            "ADD EVENT sqlserver.sql_batch_completed("
            "ACTION(sqlserver.client_app_name,sqlserver.username) "
            "WHERE ([sqlserver].[client_app_name]=N'oo-sqlserver-source')) "
            "ADD TARGET package0.ring_buffer WITH "
            "(MAX_MEMORY=16384 KB,MAX_DISPATCH_LATENCY=1 SECONDS); "
            "ALTER EVENT SESSION oo_readonly ON SERVER STATE=START;", admin=True)
    before = business_state(run)
    internal_before = cdc_state(run)
    # Exercise actual CDC reads and idle durable replay after stopping all writers.
    run.command(command, timeout=600)
    run.command(command, timeout=600)
    # Observe a native idle-scan heartbeat, rather than manufacturing internal
    # rows with the admin. Reader commands and business data remain quiescent.
    old_count = internal_before["lsn_time_mapping"]["fingerprint"]["rows"]
    deadline = time.monotonic() + 360
    while run.json_query("SELECT COUNT_BIG(*) AS n FROM cdc.lsn_time_mapping")[0]["n"] <= old_count:
        if time.monotonic() >= deadline:
            raise ValueError("native CDC idle-scan mapping append was not observed")
        time.sleep(5)
    after = business_state(run)
    internal_after = cdc_state(run)
    objects_after = run.json_query(inventory)
    ended = run.json_query("SELECT CONVERT(nvarchar(40),GETDATE(),126) AS stamp")[0]["stamp"]
    scans_after = run.json_query(telemetry)[0]
    time.sleep(2)
    rows = run.json_query(
        "SELECT CONVERT(varchar(max),CONVERT(varbinary(max),CONVERT(nvarchar(max),t.target_data)),2) AS data "
        "FROM sys.dm_xe_session_targets t JOIN sys.dm_xe_sessions s "
        "ON t.event_session_address=s.address WHERE s.name='oo_readonly'")
    xml = bytes.fromhex(rows[0]["data"]).decode("utf-16-le")
    (run.path / "reader-audit.xml").write_text(xml)
    root = ET.fromstring(xml)
    if root.attrib.get("truncated", "0") != "0":
        raise ValueError("truncated reader audit")
    events = root.findall("event")
    if not events:
        raise ValueError("empty reader audit")
    classes = {"select": 0, "snapshot_session": 0}
    for event in events:
        if event.find("action[@name='username']/value").text != "fixture_reader":
            raise ValueError("reader identity mismatch")
        statement = event.find("data[@name='batch_text']/value").text
        classes[classify(statement)] += 1
    dropped = run.json_query(
        "SELECT dropped_event_count AS n FROM sys.dm_xe_sessions WHERE name='oo_readonly'")[0]["n"]
    internal_classes = attribute_cdc(
        internal_before, internal_after, started, ended, scans_before, scans_after)
    report = {"classes": classes, "events": len(events), "dropped": dropped,
              "reader_permissions": rights,
              "objects_before": objects_before, "objects_after": objects_after,
              "business_before": before, "business_after": after,
              "cdc_before": internal_before, "cdc_after": internal_after,
              "internal_write_classes": internal_classes, "capture_job": jobs,
              "scan_before": scans_before, "scan_after": scans_after,
              "window_start": started, "window_end": ended,
              "cdc_write_policy": "only append-only zero-transaction idle-scan mappings, with scan telemetry",
              "window": "quiescent CDC read and durable idle replay; fixture admin writer stopped",
              "passed": before == after and objects_before == objects_after and dropped == 0}
    runner.write_json(run.path / "audit-report.json", report)
    if not report["passed"]:
        raise ValueError("unattributed source change or audit loss")
    return report
