#!/usr/bin/env python3
"""Extract DBA statement templates from connector doctor implementations."""
import argparse
import re

from gen_cli_reference import ROOT, write_or_check

ENGINES = [
    ("MySQL 5.7 / 8.0 / 8.4 / 9.x", "mysql/capability.rs",
     "Snapshot needs SELECT; binlog C1 additionally needs replication privileges, "
     "ROW logging and sufficient retention. The dialect selects version-specific "
     "status/parameter syntax: 5.7 uses SET GLOBAL plus my.cnf and expire_logs_days; "
     "8.0+ uses SET PERSIST and binlog_expire_logs_seconds. 8.4+ uses SHOW BINARY "
     "LOG STATUS. The mysql-binlog feature is not enabled by default (D10)."),
    ("PostgreSQL 13 / 14 / 15 / 16 / 17 / 18", "postgres/probe.rs",
     "Snapshot/C5 and logical C1 requirements are separate. C1 on a standby needs "
     "16+. PostgreSQL 18 idle slot timeout is checked. A DBA creates publications "
     "and slots; the read-only product account must not bootstrap them."),
    ("Oracle 11g / 21c / 23ai", "oracle/rules.rs",
     "11g uses SELECT ANY TRANSACTION for LogMiner; 21c/23ai use LOGMINING and "
     "CDB/PDB-aware grants. C5 uses table SELECT/FLASHBACK and catalog access. "
     "LogMiner C1 is explicit opt-in, never auto-selected. D11a permits Oracle's "
     "internal DML on SYS/SYSTEM LOGMNR-prefixed objects and same-session COMMIT "
     "during LogMiner; the reader's top-level statements remain SELECT and "
     "DBMS_LOGMNR calls only. This is not literal zero internal writes. "
     "Default C5 requires its separate zero-business-write audit."),
    ("SQL Server (snapshot / CT / CDC)", "sqlserver/mod.rs",
     "The contract emits snapshot-isolation and CT/CDC enablement statements, "
     "but does not enumerate a complete per-version reader GRANT list. "
     "That is a product-contract gap, not permission to grant db_owner."),
    ("MariaDB 10.6 / 10.11 / 11.4 / 11.8", "mariadb/mod.rs",
     "These supported lines share the monitor-privilege contract. It accepts "
     "REPLICATION CLIENT for BINLOG MONITOR and SLAVE MONITOR for REPLICA MONITOR. "
     "See the shared MySQL snapshot SELECT requirement as well."),
    ("TiDB 7.5 / 8.5 and OceanBase CE 4.x MySQL mode", "mysql/family.rs",
     "Both families require PROCESS visibility and scoped SELECT. "
     "C1 support is not inferred from MySQL wire compatibility."),
    ("ClickHouse 24.3+ / 25.x / 26.x", "olap/clickhouse.rs",
     "SELECT on the scoped database and system.mutations visibility are graded "
     "separately. A privilege list is not a claim of transactional snapshot isolation."),
    ("Doris / StarRocks", "olap/mpp.rs",
     "Doris uses SELECT_PRIV; StarRocks uses SELECT ON ALL TABLES IN DATABASE. "
     "Use only the branch matching the observed engine."),
    ("openGauss 5 / 6", "postgres/opengauss.rs",
     "Schema USAGE and scoped table SELECT are emitted by the live probe. "
     "PostgreSQL logical-replication grants are not automatically applicable."),
]
STRING = re.compile(
    r"""//[^\n]*|/\*.*?\*/|'(?:\\.|[^'\\])'|"(?P<value>(?:\\.|[^"\\])*)\"""",
    re.DOTALL)
SQL = re.compile(r"(?:GRANT |SET (?:GLOBAL|PERSIST) |hostssl |ALTER (?:SYSTEM|ROLE|DATABASE|TABLE) |"
                 r"CREATE (?:USER|PUBLICATION|REPLICATION SLOT) |"
                 r"EXEC sys\.|SHUTDOWN IMMEDIATE)")


def production_source(source):
    return re.sub(r"(?ms)^#\[cfg\(test\)\]\nmod \w+ \{.*?^\}",
                  lambda m: "\n" * m[0].count("\n"), source)


def statements(source):
    source = production_source(source)
    found = []
    for match in STRING.finditer(source):
        value = match["value"]
        if value is None or value.strip() == "GRANT" or not SQL.match(value):
            continue
        # Rust escaped newlines remove following indentation.
        value = re.sub(r"\\\n\s*", "", value)
        value = value.replace(r"\n", "\n").replace(r'\"', '"').replace(r"\\", "\\")
        line = source.count("\n", 0, match.start()) + 1
        if "{privilege}" in value:
            loops = list(re.finditer(r'for privilege in \[([^\]]+)\]', source[:match.start()]))
            if not loops:
                raise ValueError("Unresolved doctor privilege loop")
            for privilege in re.findall(r'"([^"]+)"', loops[-1][1]):
                found.append((line, value.replace("{privilege}", privilege)))
        else:
            found.append((line, value))
    return found


def render():
    out = [
        "# DBA grants and prerequisites", "",
        "Generated by `python3 tools/docs/gen_dba_grants.py`; do not hand-edit SQL.",
        "These are **source templates**, not a script to execute wholesale. Braces "
        "are Rust substitutions; account, schema and table quoting is performed by "
        "the connector. Run `oo doctor --config stack.yaml --json` for observed "
        "`capabilities.*.requirements`: `name`, `observed`, `required`, and "
        "`dba_statement`. A null statement means no automatic remedy is supplied.",
        "",
        "A DBA applies only the requirements for the requested capability, on a "
        "separate administrative connection. Never give the product reader DDL/DML "
        "authority merely to clear doctor. Parameter changes, restarts, supplemental "
        "logging, slots and publications require DBA review. Re-run doctor afterward.",
        "",
        "Version headings identify contract branches, not new engine/version test "
        "results. The support matrix remains the acceptance authority.", "",
    ]
    for title, relative, note in ENGINES:
        path = ROOT / "crates/oo-connectors/src" / relative
        rows = statements(path.read_text())
        if not rows:
            raise ValueError(f"No DBA statements found in {relative}")
        out.extend([f"## {title}", "", note, ""])
        for line, sql in rows:
            source = path.relative_to(ROOT)
            out.extend([f"Source: [`{relative}:{line}`](../../{source}#L{line}).", "",
                        "```sql", sql, "```", ""])
    out.extend([
        "## Contract gaps", "",
        "SQL Server does not yet emit a complete reader GRANT list per server "
        "version. Oracle account/session prerequisites and actual catalog-view "
        "requirements depend on the observed container and selected tables. "
        "These templates cannot replace the live doctor report. MongoDB/OpenSearch "
        "use non-SQL authorization contracts and are outside this SQL grant list.", "",
    ])
    return "\n".join(out)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    write_or_check(ROOT / "docs/database-support/dba-grants.md", render(), args.check)
