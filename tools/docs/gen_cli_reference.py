#!/usr/bin/env python3
"""Render actual native and npm help without consulting a user's profile."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "docs/reference/cli.md"
GROUPS = {"sql", "knowledge", "ontology", "token", "config"}


def commands(text):
    """Discover advertised commands, including pipe-separated alternatives."""
    found = set()
    for line in text.splitlines():
        match = re.match(r"\s*(?:Usage:\s*)?oo ([a-z][a-z|-]*)(.*)", line)
        if not match:
            continue
        first, rest = match.groups()
        for root in first.split("|"):
            found.add((root,))
            child = re.match(r" ([a-z][a-z|-]*)(?:\s|$)", rest)
            if root in GROUPS and child:
                found.update((root, leaf) for leaf in child[1].split("|"))
    return found


def write_or_check(path, content, check):
    if check:
        if not path.is_file() or path.read_text() != content:
            raise SystemExit(f"Generated documentation differs: {path.relative_to(ROOT)}")
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)


def render(binary):
    # Stage the real wrapper with a verified native manifest, not an installed
    # user's package. Help must not require a profile, credentials or network.
    evidence = ROOT / "evidence"
    evidence.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="docs-help-", dir=evidence) as directory:
        temp = Path(directory)
        package = temp / "package"
        shutil.copytree(ROOT / "packages/cli/bin", package / "bin")
        platform = subprocess.check_output(
            ["node", "-p", "process.platform+'-'+process.arch"], text=True).strip()
        native = package / "native" / platform / "oo"
        native.parent.mkdir(parents=True)
        shutil.copy2(binary, native)
        (package / "native/manifest.json").write_text(json.dumps({
            "schema_version": 1, "binaries": {platform: {
                "path": f"native/{platform}/oo",
                "sha256": hashlib.sha256(native.read_bytes()).hexdigest()}}}))
        home = temp / "home"
        home.mkdir()
        env = {k: v for k, v in os.environ.items()
               if k in ("PATH", "SYSTEMROOT", "TMPDIR")}
        env.update(HOME=str(home), NO_COLOR="1", TERM="dumb", LC_ALL="C")
        runner = ["node", str(package / "bin/oo.mjs")]

        def help_for(command):
            result = subprocess.run([*runner, *command, "--help"], env=env,
                                    capture_output=True, text=True, timeout=30)
            if command == ("help",) and result.returncode and "CONFIG_ARGUMENTS" in result.stderr:
                return f"Exit {result.returncode}\n{result.stderr.rstrip()}"
            if result.returncode or result.stderr:
                raise RuntimeError(f"Help failed: oo {' '.join(command)}: {result.stderr}")
            return result.stdout.rstrip()

        top = help_for(())
        pending = commands(top)
        reports = {(): top}
        while pending:
            command = min(pending)
            pending.remove(command)
            if command in reports:
                continue
            reports[command] = help_for(command)
            pending.update(commands(reports[command]) - reports.keys())
        out = [
            "# CLI reference", "",
            "Generated by `python3 tools/docs/gen_cli_reference.py --binary target/debug/oo`.",
            "Do not edit this file. `--check` compares every captured help byte.",
            "The npm wrapper is staged with the supplied native binary and an empty HOME.",
            "No credentials, database or Gateway are needed. Rebuild the binary before checking.",
            "Some commands intentionally share help; each advertised command is still invoked.",
            "",
        ]
        for command, text in sorted(reports.items()):
            label = " ".join(("oo", *command, "--help"))
            out.extend([f"## `{label}`", "", "```text", text, "```", ""])
        return "\n".join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, default=ROOT / "target/debug/oo")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    write_or_check(OUTPUT, render(args.binary.resolve()), args.check)


if __name__ == "__main__":
    main()
