-- Least privilege after the users exist. No ANY, no LOGMINING.
SET DEFINE OFF
SET FEEDBACK OFF
SET HEADING OFF
SET PAGESIZE 0
SET LINESIZE 200
SET SERVEROUTPUT ON SIZE UNLIMITED
WHENEVER SQLERROR EXIT SQL.SQLCODE

ALTER SESSION SET CONTAINER = FREEPDB1;

GRANT CREATE SESSION TO oo34_reader;
GRANT SELECT, FLASHBACK ON oo34_fix.t_batch TO oo34_reader;
GRANT SELECT, FLASHBACK ON oo34_fix.t_wide TO oo34_reader;
GRANT SELECT, FLASHBACK ON oo34_fix.t_ts TO oo34_reader;
GRANT EXECUTE ON sys.dbms_flashback TO oo34_reader;

DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM dba_tables WHERE owner = 'OO34_FIX' AND table_name = 'T_BOOL';
  IF n = 1 THEN
    EXECUTE IMMEDIATE 'GRANT SELECT, FLASHBACK ON oo34_fix.t_bool TO oo34_reader';
    DBMS_OUTPUT.PUT_LINE('bool|granted');
  ELSE
    DBMS_OUTPUT.PUT_LINE('bool|absent');
  END IF;
END;
/

GRANT CREATE SESSION TO oo34_noflash;
GRANT SELECT ON oo34_fix.t_batch TO oo34_noflash;

BEGIN EXECUTE IMMEDIATE 'NOAUDIT POLICY oo_dl01w1_34_acts';
EXCEPTION WHEN OTHERS THEN NULL; END;
/
BEGIN EXECUTE IMMEDIATE 'DROP AUDIT POLICY oo_dl01w1_34_acts';
EXCEPTION WHEN OTHERS THEN NULL; END;
/

CREATE AUDIT POLICY oo_dl01w1_34_acts ACTIONS ALL;
AUDIT POLICY oo_dl01w1_34_acts BY oo34_reader, oo34_noflash;

PROMPT grants|done
EXIT
