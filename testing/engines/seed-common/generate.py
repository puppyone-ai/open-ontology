#!/usr/bin/env python3
"""Deterministic SQL fixture; the database expands digit products in bulk."""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate(engine, version="", scale=2_000_000, tables=200):
    if scale < 1 or scale > 10_000_000 or not 0 <= tables <= 5000:
        raise ValueError("scale must be 1..10000000; tables must be 0..5000")
    oracle = engine == "oracle"
    text = "VARCHAR2(100 CHAR)" if oracle else "VARCHAR(100)"
    integer = "NUMBER(19)" if oracle else "BIGINT"
    auto = {"mysql": "BIGINT AUTO_INCREMENT", "postgres": "BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000)",
            "oracle": "NUMBER(19)"}[engine]
    preamble = (ROOT / engine / "seed" / "preamble.sql").read_text()
    if oracle and version and not version.startswith("11"):
        preamble = preamble.replace(
            "CREATE TABLE partition_events (id NUMBER(19), month_no INTEGER, PRIMARY KEY(id,month_no));",
            "CREATE TABLE partition_events (id NUMBER(19), month_no INTEGER, PRIMARY KEY(id,month_no)) "
            "PARTITION BY RANGE(month_no) (PARTITION p1 VALUES LESS THAN(2), PARTITION p2 VALUES LESS THAN(MAXVALUE));")
        preamble = preamble.replace("document CLOB,", "document CLOB CHECK(document IS JSON),")
    yield preamble
    lob = (" || ".join(["TO_CLOB(RPAD('x',2000,'x'))"] * 8) if oracle
           else "REPEAT('x',16000)")
    yield f"UPDATE type_edges SET text_lob={lob} WHERE id=1;\n"
    if oracle:
        yield "CREATE SEQUENCE fixture_ids START WITH 1000;\n"
    yield f"CREATE TABLE regions (id {auto} PRIMARY KEY, name {text});\n"
    if oracle:
        yield ("CREATE OR REPLACE TRIGGER region_id BEFORE INSERT ON regions FOR EACH ROW\n"
               "WHEN (new.id IS NULL) BEGIN :new.id := fixture_ids.NEXTVAL; END;\n/\n")
    for table, parent, fk in [("areas", "regions", "region_id"), ("sites", "areas", "area_id")]:
        yield f"CREATE TABLE {table} (id {integer} PRIMARY KEY, {fk} {integer}, name {text}, FOREIGN KEY({fk}) REFERENCES {parent}(id));\n"
    yield f"CREATE TABLE codes (code {integer} PRIMARY KEY, label {text});\n"
    yield (f"CREATE TABLE customers (id {integer} PRIMARY KEY, site_id {integer}, "
           f"name {text}, phone_synthetic {text}, national_id_synthetic {text}, note {text}, FOREIGN KEY(site_id) REFERENCES sites(id));\n")
    yield (f"CREATE TABLE orders (id {integer} PRIMARY KEY, customer_id {integer}, "
           f"status_code {integer}, amount DECIMAL(18,4), qty {integer}, ordered_at TIMESTAMP, "
           "FOREIGN KEY(customer_id) REFERENCES customers(id), FOREIGN KEY(status_code) REFERENCES codes(code));\n")
    yield (f"CREATE TABLE shipments (id {integer} PRIMARY KEY, order_id {integer}, "
           f"site_id {integer}, shipped_at TIMESTAMP, FOREIGN KEY(order_id) REFERENCES orders(id));\n")
    yield f"CREATE TABLE calendar (day_id {integer} PRIMARY KEY, day_date DATE, month_no {integer});\n"
    yield f"CREATE TABLE order_lines (order_id {integer}, line_no {integer}, qty {integer}, PRIMARY KEY(order_id,line_no), FOREIGN KEY(order_id) REFERENCES orders(id));\n"
    yield f"CREATE TABLE unique_only (code {text} NOT NULL UNIQUE, value_no {integer});\n"
    yield f"CREATE TABLE no_key (value_no {integer}, note {text});\n"
    yield f"CREATE TABLE events (id {integer} PRIMARY KEY, order_id {integer}, event_no {integer});\n"
    yield f"CREATE TABLE growth_events (id {integer} PRIMARY KEY, order_id {integer});\n"
    yield "CREATE TABLE wide_rows (\n" + ",\n".join(f"c{i:03d} {integer}" + (" PRIMARY KEY" if i == 0 else "") for i in range(300)) + ");\n"
    for month in range(1, 13):
        yield f"CREATE TABLE log_2026{month:02d} (id {integer} PRIMARY KEY, order_id {integer});\n"
    for name in ["orders_audit", "orders_backup"]:
        yield f"CREATE TABLE {name} (id {integer}, order_id {integer}, note {text});\n"
    for i in range(tables):
        yield f"CREATE TABLE small_{i:04d} (id {integer} PRIMARY KEY, value_no {integer});\n"
        yield f"INSERT INTO small_{i:04d} VALUES (1,{i});\n"
    for i in range(1, 3):
        yield f"INSERT INTO regions VALUES ({i},'Region {i}');\n"
    for i in range(1, 5):
        yield f"INSERT INTO areas VALUES ({i},{1+(i-1)//2},'Area {i}');\n"
    for i in range(1, 9):
        yield f"INSERT INTO sites VALUES ({i},{1+(i-1)//2},'Site {i}');\n"
    for i, label in enumerate(["New", "Shipped", "Closed"], 1):
        yield f"INSERT INTO codes VALUES ({i},'{label}');\n"
    for i in range(1, 25):
        note = "NULL" if i % 3 == 0 else ("''" if i % 3 == 1 else "'memo'")
        yield f"INSERT INTO customers VALUES ({i},{1+(i-1)%8},'Customer {i}','SYN-PHONE-{i:04d}','SYN-ID-{i:06d}',{note});\n"
    for i in range(1, 121):
        date = f"2026-{1+(i-1)//60:02d}-{1+(i-1)%28:02d} 12:34:56"
        timestamp = f"TIMESTAMP '{date}'" if engine != "mysql" else f"'{date}'"
        yield f"INSERT INTO orders VALUES ({i},{1+(i-1)%24},{1+(i-1)%3},{i}.1250,{1+i%5},{timestamp});\n"
        yield f"INSERT INTO order_lines VALUES ({i},1,1);\nINSERT INTO order_lines VALUES ({i},2,2);\n"
        if i % 4:
            yield f"INSERT INTO shipments VALUES ({i},{i},{1+(i-1)%8},{timestamp});\n"
    for i in range(1, 29):
        yield f"INSERT INTO calendar VALUES ({i},DATE '2026-01-{i:02d}',1);\n"
    for i, value in enumerate(["Alpha", "alpha-2", "caf\u00e9", "CAFE-2", "trail ", "trail-2", "emoji-\U0001f680"], 1):
        yield f"INSERT INTO string_keys VALUES ('{value}',{i});\n"
    yield "INSERT INTO unique_only VALUES ('only',1);\nINSERT INTO no_key VALUES (1,NULL);\nINSERT INTO no_key VALUES (1,'');\n"
    yield "INSERT INTO wide_rows VALUES (" + ",".join(str(i) for i in range(300)) + ");\n"
    for month in range(1, 13):
        yield f"INSERT INTO log_2026{month:02d} VALUES ({month},{month});\n"
    yield "INSERT INTO orders_audit VALUES (1,1,'synthetic');\nINSERT INTO orders_backup VALUES (1,1,'synthetic');\n"
    yield "CREATE TABLE seed_digits (d INTEGER PRIMARY KEY);\n"
    for i in range(10):
        yield f"INSERT INTO seed_digits VALUES ({i});\n"
    n = "1+" + "+".join(f"d{i}.d*{10**i}" for i in range(7))
    cross = " CROSS JOIN ".join(f"seed_digits d{i}" for i in range(7))
    # Filter upper digits before expanding: small smoke runs do not scan 10M rows.
    limits = " AND ".join(f"d{i}.d<={min(9, (scale-1)//(10**i))}" for i in range(7))
    yield (f"INSERT INTO events SELECT n,MOD(n-1,120)+1,MOD(n,7) FROM "
           f"(SELECT {n} AS n FROM {cross} WHERE {limits}) seed_rows WHERE n<={scale};\n")
    yield "INSERT INTO growth_events SELECT id,order_id FROM events WHERE id<=100;\n"
    yield "DROP TABLE seed_digits;\nCREATE VIEW order_totals AS SELECT customer_id,SUM(amount) AS total FROM orders GROUP BY customer_id;\n"
    yield "COMMIT;\n"


def growth(engine, after, count):
    """Admin-only append batches for a concurrent growth writer."""
    if after < 100 or count < 1 or count > 10_000_000:
        raise ValueError("growth requires after>=100 and count in 1..10000000")
    if engine == "oracle":
        rows = f"SELECT LEVEL+{after} AS n FROM dual CONNECT BY LEVEL<={count}"
    elif engine == "postgres":
        rows = f"SELECT generate_series({after+1},{after+count}) AS n"
    else:
        digits = "(SELECT 0 AS d UNION ALL " + " UNION ALL ".join(f"SELECT {i}" for i in range(1, 10)) + ")"
        n = "+".join(f"d{i}.d*{10**i}" for i in range(7))
        source = " CROSS JOIN ".join(f"{digits} d{i}" for i in range(7))
        rows = f"SELECT {n}+{after+1} AS n FROM {source} WHERE {n}<{count}"
    return f"INSERT INTO growth_events SELECT n,MOD(n-1,120)+1 FROM ({rows}) growth_rows;\nCOMMIT;\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--engine", choices=["mysql", "postgres", "oracle"], required=True)
    parser.add_argument("--version", default="")
    parser.add_argument("--scale", type=int, default=2_000_000)
    parser.add_argument("--tables", type=int, default=200)
    parser.add_argument("--growth-after", type=int, help="append after this id, using the admin connection")
    parser.add_argument("--growth-count", type=int, default=10000)
    args = parser.parse_args()
    if args.growth_after is not None:
        sys.stdout.write(growth(args.engine, args.growth_after, args.growth_count))
        return
    for sql in generate(args.engine, args.version, args.scale, args.tables):
        sys.stdout.write(sql)


if __name__ == "__main__":
    main()
