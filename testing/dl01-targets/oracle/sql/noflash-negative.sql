-- User with SELECT and without FLASHBACK. AS OF SCN must fail.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET DEFINE ON
SET FEEDBACK OFF
SET HEADING OFF
SET PAGESIZE 0
SET VERIFY OFF

DECLARE
  v VARCHAR2(40);
BEGIN
  EXECUTE IMMEDIATE
    'SELECT TO_CHAR(d, ''YYYY-MM-DD HH24:MI:SS'') FROM oo_fix.t_date AS OF SCN &1 WHERE id = 1'
    INTO v;
  DBMS_OUTPUT.PUT_LINE('noflash|accepted|' || v);
EXCEPTION
  WHEN OTHERS THEN
    DBMS_OUTPUT.PUT_LINE('noflash|rejected|' || SQLCODE || '|' || SQLERRM);
END;
/
PROMPT noflash|done
EXIT
