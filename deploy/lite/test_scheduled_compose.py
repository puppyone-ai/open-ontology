#!/usr/bin/env python3
"""Seven actual lite services/jobs; fixture-admin bootstrap, replay initial model.

Uses deploy/lite/compose.yaml with fixture-only published loopback ports and
initial database setup. Source SQL writes are issued only by this test admin.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import threading
import time

from test_scheduled_live import Scheduled, PROJECT, ROOT, retained, scheduler, lifecycle


class ComposeScheduled(Scheduled):
    def __init__(self, out, image):
        super().__init__(out, 'postgres', None)
        self.image = image
        self.lite = out / '.oo/lite'
        self.lite.mkdir(parents=True, mode=0o700)
        self.lite.parent.chmod(0o700)
        self.project = 'oo-a-lite-' + hashlib.sha256(str(self.lite.resolve()).encode()).hexdigest()[:16]
        self.argv = ['compose', '-p', self.project, '-f', str(self.lite / 'compose.yaml'),
                     '--profile', 'integration']
        self.env = dict(os.environ, OO_LITE_LANE='m', OO_LITE_STATE=str(self.lite),
                        OO_LITE_RUNTIME_IMAGE=image, OO_LITE_UID=str(os.getuid()), OO_LITE_GID=str(os.getgid()))
        self.env['OO_LITE_SUBNET'] = lifecycle.subnet(self.project, self.env)
        self.gateway_port = self.fixture.free_port()
        self.db.start = self.start_databases
        self.db.close = lambda: None  # The compose owner performs the single teardown.
        command = self.run.command

        def fixture_command(argv, **kwargs):
            if argv[:2] == ['docker', 'cp'] and argv[-1].startswith(self.db.name + ':/tmp/'):
                name = Path(argv[2]).name
                argv = ['docker', 'exec', '-u', 'root', self.db.name, 'cp',
                        '/run/private/' + name, '/tmp/' + name]
            return command(argv, **kwargs)
        self.run.command = fixture_command

    def docker(self, args, timeout=180):
        result = subprocess.run(['docker', *args], env=self.env, capture_output=True, timeout=timeout)
        with (self.out / 'compose.log').open('ab') as log:
            log.write(result.stdout + result.stderr)
        assert result.returncode == 0, 'compose command; see compose.log'
        return result.stdout

    def inside(self, path):
        return '/evidence/' + str(Path(path).relative_to(self.out))

    def start_databases(self):
        for name in ('work', 'home', 'pki'):
            (self.lite / name).mkdir(mode=0o700)
        shutil.copy(ROOT / 'deploy/lite/postgres.sh', self.lite / 'postgres.sh')
        shutil.copy(ROOT / 'deploy/lite/compose.yaml', self.lite / 'base.yaml')
        # Credentials are generated by AgentDB; no passwords in env or argv.
        db = {'image': 'docker.io/library/postgres@sha256:839fbb5a4942a7758dd93e18b42ea5649807491a0545b5eeeb8f0b8bb11857a5',
              'entrypoint': ['bash', '-c', 'cp /run/private/password /tmp/pw; chown postgres:postgres /tmp/pw; chmod 600 /tmp/pw; exec docker-entrypoint.sh postgres'],
              'environment': {'POSTGRES_PASSWORD_FILE': '/tmp/pw'},
              'volumes': [str(self.db.directory) + ':/run/private:ro']}
        services = {name: dict(db) for name in ('agent-db', 'control-db')}
        services['agent-db']['ports'] = ['127.0.0.1::5432']
        for name in ('builder', 'worker', 'scheduler', 'gateway', 'model-egress'):
            services[name] = {'volumes': [str(self.out) + ':/evidence']}
        services['gateway'].update(entrypoint=['oo-gateway', self.inside(self.runtime)],
                                   ports=[f'127.0.0.1:{self.gateway_port}:8443'])
        services['builder'].update(entrypoint=['python3', '/work/one-shot.py'], command=[])
        scheduler.save(self.lite / 'fixture.json', {'services': services})
        merged = self.docker(['compose', '-p', self.project, '-f', str(self.lite / 'base.yaml'), '-f', str(self.lite / 'fixture.json'),
                              '--profile', 'integration', 'config', '--format', 'json'])
        lifecycle.write(self.lite / 'compose.yaml', merged)
        lifecycle.write(self.lite / 'owner.json', json.dumps({'image': self.image, 'lane': 'm',
                        'project': self.project, 'subnet': self.env['OO_LITE_SUBNET']}).encode())
        self.docker(self.argv + ['up', '-d', '--wait', 'agent-db', 'control-db'])
        self.db.created = True
        self.db.name = self.docker(self.argv + ['ps', '-q', 'agent-db']).decode().strip()
        port = self.docker(self.argv + ['port', 'agent-db', '5432']).decode().strip()
        self.db.port = int(port.rsplit(':', 1)[1])
        self.db.sql("CREATE COLLATION fixture_ci (provider=icu,locale='und-u-ks-level1',deterministic=false);")

    def command(self, argv, label, data=None):
        if label == 'server-sign':
            path = self.db.directory / 'server-ext'
            path.write_text(path.read_text().replace('DNS:localhost,IP:127.0.0.1',
                            'DNS:localhost,DNS:agent-db,DNS:control-db,DNS:gateway,IP:127.0.0.1'))
        return super().command(argv, label, data)

    def load(self, prefix, run):
        stack = json.loads(self.stack.read_text())
        stack['sources'][0].update(host='agent-db', port=5432)
        scheduler.save(self.stack, stack)
        target = json.loads(self.target.read_text())
        target.update(host='agent-db', port=5432, local_fixture=False, tls_ca={'secret_ref': 'source-ca'})
        container_target = self.root / 'container-target.json'
        scheduler.save(container_target, target)
        raw = self.docker(self.argv + ['run', '--rm', '--no-deps', '--entrypoint', 'oo-load', 'worker',
            *prefix, '--stack', self.inside(self.stack), '--source', 'owned', '--target', self.inside(container_target),
            '--secrets-dir', self.inside(self.db.directory), '--run-id', run])
        (self.out / ('load-' + run + '.stdout')).write_bytes(raw)

    def start_gateway(self):
        free = self.fixture.free_port
        self.fixture.free_port = lambda: self.gateway_port
        try:
            super().start_gateway()
        finally:
            self.fixture.free_port = free

    def control_sql(self, text):
        result = subprocess.run(['docker', *self.argv, 'exec', '-T', 'control-db', 'psql', '-U', 'postgres',
                                 '-X', '-qAt', '-v', 'ON_ERROR_STOP=1'], env=self.env,
                                input=text, text=True, capture_output=True)
        with (self.out / 'control.log').open('a') as log:
            log.write(result.stdout + result.stderr)
        assert result.returncode == 0, 'control SQL; see control.log'
        return result.stdout.strip()

    def install_jobs(self):
        base = ROOT / 'crates/oo-jobs/migrations'
        names = ['0000_bootstrap_roles.sql', '0001_jobs_control_expand.sql',
                 '0002_event_project_binding_expand.sql', '0003_job_lease_operations_expand.sql']
        versions = ['jobs-bootstrap/1', 'jobs-control/1', 'jobs-event-project/1', 'jobs-lease-operations/1']
        sql = ['BEGIN; SELECT pg_advisory_xact_lock(6401202601);']
        for i, name in enumerate(names):
            if i == 1:
                sql.append('SET LOCAL ROLE oo_jobs_owner;')
            sql.append((base / name).read_text())
        for version, name in zip(versions, names):
            digest = hashlib.sha256((base / name).read_bytes()).hexdigest()
            sql.append(f"INSERT INTO jobs.schema_migrations(version,checksum,phase,filename) VALUES('{version}','{digest}','expand','{name}');")
        sql.append('COMMIT;')
        self.control_sql('\n'.join(sql))
        self.control_sql((ROOT / 'deploy/lite/cycle_events.sql').read_text())
        self.control_sql(f"SET ROLE oo_jobs_runtime; INSERT INTO jobs.schedules(project_id,kind,config_version,artifact_digest,dedupe_prefix,next_run_at) VALUES('{PROJECT}','lite_retained','v1',repeat('a',64),'lite',clock_timestamp());")

    def prepare_runtime(self):
        self.gateway.terminate()
        self.gateway.wait(timeout=15)
        self.gateway = None
        self.log.close()
        self.install_jobs()
        migration = (ROOT / 'tools/gateway-token-store/migrations/oo_token_control_v2.sql').read_bytes()
        self.db.sql(migration.decode() + "\nINSERT INTO oo_token_lifecycle.migration VALUES(2,'" +
                    hashlib.sha256(migration).hexdigest() + "');")
        # Fixture setup of the control server's TLS; product clients verify it.
        control = self.docker(self.argv + ['ps', '-q', 'control-db']).decode().strip()
        for name in ('server-key', 'server-cert', 'source-ca'):
            self.docker(['exec', '-u', 'root', control, 'cp', '/run/private/' + name, '/tmp/' + name])
        self.docker(['exec', '-u', 'root', control, 'sh', '-c',
                     'chown postgres:postgres /tmp/server-* /tmp/source-ca; chmod 600 /tmp/server-key'])
        self.control_sql("ALTER SYSTEM SET ssl='on'; ALTER SYSTEM SET ssl_cert_file='/tmp/server-cert'; ALTER SYSTEM SET ssl_key_file='/tmp/server-key'; SELECT pg_reload_conf();")
        endpoint = {'host': 'agent-db', 'port': 5432, 'database': 'postgres'}
        scheduler.save(self.runtime / 'endpoint.json', endpoint)
        gateway = json.loads((self.runtime / 'config.json').read_text())
        gateway['listen'] = '0.0.0.0:8443'
        scheduler.save(self.runtime / 'config.json', gateway)
        (self.runtime / 'listen.addr').unlink()
        publisher = json.loads((self.root / 'publisher.json').read_text())
        publisher.update(host='agent-db', port=5432,
                         password_file=self.inside(self.db.directory / 'password'),
                         ca_file=self.inside(self.db.directory / 'source-ca'))
        scheduler.save(self.root / 'container-publisher.json', publisher)
        home = self.lite / 'home'
        secret = self.db.password
        lifecycle.write(home / '.pgpass', f'agent-db:5432:*:postgres:{secret}\ncontrol-db:5432:*:postgres:{secret}\n'.encode())
        service = ''.join(f'[{name}]\nhost={name}-db\nport=5432\ndbname=postgres\nuser=postgres\nsslmode=verify-full\nsslrootcert={self.inside(self.db.directory / "source-ca")}\n' for name in ('agent', 'control'))
        lifecycle.write(home / '.pg_service.conf', service.encode())
        config = self.config()
        config = json.loads(json.dumps(config).replace(str(self.out), '/evidence'))
        config['control_psql_command'] = ['psql', 'service=control']
        config['work_dir'] = '/work/cycles'
        cycle = config['cycle']
        cycle.update(loader='oo-load', publisher='release-coordinator',
                     target=self.inside(self.root / 'container-target.json'),
                     publisher_config=self.inside(self.root / 'container-publisher.json'))
        cycle['builder']['psql_command'] = ['psql', 'service=agent']
        cycle['gateway_probe']['url'] = 'https://gateway:8443'
        work = self.lite / 'work'
        (work / 'operator').mkdir()
        scheduler.save(work / 'operator/schedule.json', config)
        shutil.copy(ROOT / 'deploy/lite/scheduler.py', work / 'scheduler.py')
        (work / 'one-shot.py').write_text('import json,pathlib,scheduler\nc=json.loads(pathlib.Path("/work/operator/schedule.json").read_text())\np=pathlib.Path("/work/builder-completed");p.mkdir()\nr=scheduler.data_only(c["cycle"],"baseline",p)\nscheduler.save(p/"result.json",r)\nassert r["stage"]=="data_only"\n')
        stack = json.loads(self.stack.read_text())
        stack['gateway'] = {'public_url': self.origin}
        scheduler.save(self.out / 'stack.json', stack)
        scheduler.save(work / 'stack.json', stack)
        store = home / '.config/open-ontology/secrets'
        store.mkdir(parents=True, mode=0o700)
        lifecycle.write(store / 'absent-model-key', b'synthetic-unused-model-key')
        for name, path in [('token', self.root / 'client-token'), ('ca', self.runtime / 'ca.crt'),
                           ('cert', self.root / 'client.crt'), ('key', self.root / 'client.key')]:
            lifecycle.write(self.lite / 'pki' / name, path.read_bytes())
        lifecycle.write(self.lite / 'health-client.json', b'{"token":"token","ca":"ca","cert":"cert","key":"key"}')

    def cycles(self):
        self.prepare_runtime()
        self.docker(self.argv + ['up', '-d', 'builder', 'gateway', 'model-egress', 'scheduler', 'worker'])
        results = []
        for name, expected, count in [('noop', '10', 1), ('data-change', '11', 2)]:
            if name == 'data-change':
                self.source_sql('UPDATE app.items SET amount=11;')
                self.control_sql('UPDATE jobs.schedules SET next_run_at=clock_timestamp();')
            for _ in range(120):
                successes = int(self.control_sql("SELECT count(*) FROM jobs.tasks WHERE state='succeeded';"))
                failures = int(self.control_sql("SELECT count(*) FROM jobs.tasks WHERE state='failed';"))
                assert failures == 0, 'scheduled failure; inspect cycle receipts'
                if successes >= count:
                    break
                time.sleep(1)
            else:
                raise AssertionError('scheduled cycle timeout')
            query = self.http()
            assert query['status'] == 200 and query['body']['rows'] == [[expected]], query
            for _ in range(30):
                status = subprocess.run([str(retained.BIN / 'oo'), 'status', '--config', str(self.out / 'stack.json'), '--json'],
                                        capture_output=True)
                if status.returncode == 0:
                    break
                time.sleep(1)
            (self.out / (name + '-status.json')).write_bytes(status.stdout)
            report = json.loads(status.stdout)
            assert report['healthy'] and report['last_success'] and report['next_due'], report
            results.append({'cycle': name, 'query': query, 'status': report})
            if name == 'noop':
                def read():
                    while not self.stop.is_set():
                        self.reads.append(self.http())
                        self.stop.wait(.02)
                self.worker = threading.Thread(target=read)
                self.worker.start()
        self.stop.set()
        self.worker.join(timeout=35)
        bindings = {entry['query']['body']['rows'][0][0]:
                    (entry['query']['publication'], entry['query']['vector']) for entry in results}
        assert self.reads and all(query['status'] == 200 and
            (query['publication'], query['vector']) == bindings[query['body']['rows'][0][0]]
            for query in self.reads)
        assert len(set(bindings.values())) == 2
        assert (self.lite / 'work/usage.jsonl').read_bytes() == b''
        completed = json.loads((self.lite / 'work/builder-completed/result.json').read_text())
        assert completed['stage'] == 'data_only' and completed['model_calls'] == 0
        scheduler.save(self.out / 'compose-result.json', {'status': 'passed', 'seven_healthy': True,
            'version': self.db.sql('SHOW server_version').strip(), 'cycles': results,
            'continuous_queries': len(self.reads), 'query_errors': 0, 'scheduled_model_calls': 0,
            'initial_model_basis': 'deterministic_test_transport', 'runtime_image': self.image})

    def close(self):
        try:
            super().close()
        finally:
            ids = self.docker(self.argv + ['ps', '-aq']).decode().split()
            for cid in ids:
                labels = json.loads(self.docker(['inspect', '--format', '{{json .Config.Labels}}', cid]))
                assert labels.get('oo.lane') == 'm' and labels.get('com.docker.compose.project') == self.project
            self.docker(self.argv + ['logs', '--no-color'])
            self.docker(self.argv + ['down', '--volumes'])
            # Generated fixture credentials only; never preserve secrets in evidence.
            for path in (self.db.directory, self.lite / 'home', self.lite / 'pki'):
                if path.exists():
                    shutil.rmtree(path)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run-id', required=True)
    parser.add_argument('--image', required=True)
    args = parser.parse_args()
    assert args.run_id and all(c.isalnum() or c == '-' for c in args.run_id)
    os.umask(0o077)
    os.environ['OO_SELFBUILD_BUDGET_BIN'] = str(retained.BIN / 'selfbuild-budget')
    out = ROOT / 'evidence' / args.run_id
    out.mkdir(mode=0o700)
    live = ComposeScheduled(out, args.image)
    try:
        live.start()
        live.cycles()
    finally:
        live.close()
        retained.cycles.checksums(out)


if __name__ == '__main__':
    main()
