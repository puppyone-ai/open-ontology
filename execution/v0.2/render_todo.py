#!/usr/bin/env python3
"""Render execution/v0.2/TODO.md from state.json and check it against the plan and ledger.

`--check` fails when TODO.md is stale or any rule below is violated; it never
claims product verification.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
STATE = HERE / 'state.json'
LEDGER = HERE / 'ledger.md'
TODO = HERE / 'TODO.md'
PLAN = ROOT / 'specs/product-loops-v0.2-plan.md'

# Plan §2 acceptance levels, in order. `blocked` is outside the order.
LEVELS = ['pending', 'in_progress', 'author_complete', 'reviewed', 'integrated', 'released']
STATUSES = set(LEVELS) | {'blocked'}
KINDS = {'plan', 'dispatch', 'delivery', 'review', 'integrate', 'sprint-exit',
         'deviation', 'correction', 'blocked', 'unblocked'}
PLAN_ROW = re.compile(r'^\| (S(\d)-([A-Z])-\d{2}) \| [A-Z] \| ([^|]+)\|', re.M)
LEDGER_ROW = re.compile(r'^\| (E\d{3}) \| (\d{4}-\d{2}-\d{2}) \| ([a-z-]+) \| ([^|]*) \| ([^|]*) \| (.+) \|$', re.M)
TASK_ID = re.compile(r'\bS\d-[A-Z]-\d{2}\b')


def level(status: str) -> int:
    return LEVELS.index(status) if status in LEVELS else -1


def is_ancestor(sha: str, branch: str) -> bool | None:
    try:
        r = subprocess.run(['git', '-C', str(ROOT), 'merge-base', '--is-ancestor', sha, branch],
                           capture_output=True, timeout=20)
    except (OSError, subprocess.TimeoutExpired):
        return None
    return {0: True, 1: False}.get(r.returncode)


def inspect(state: dict, plan: str, ledger: str) -> list[str]:
    errors: list[str] = []
    plan_rows = PLAN_ROW.findall(plan)
    plan_ids = [r[0] for r in plan_rows]
    plan_lane = {r[0]: r[2] for r in plan_rows}
    tasks = state.get('tasks', [])
    ids = [t.get('id') for t in tasks]
    if ids != plan_ids:
        errors.append(f'state.json tasks differ from plan TODO rows: missing={sorted(set(plan_ids)-set(ids))} extra={sorted(set(ids)-set(plan_ids))} order_equal={ids==plan_ids}')

    rows = LEDGER_ROW.findall(ledger)
    exits = set()
    for n, (eid, _, kind, task_cell, _, event) in enumerate(rows, 1):
        if eid != f'E{n:03d}':
            errors.append(f'ledger IDs must be sequential: expected E{n:03d}, found {eid}')
        if kind not in KINDS:
            errors.append(f'{eid}: unknown event kind {kind}')
        for t in TASK_ID.findall(task_cell):
            if t not in plan_lane:
                errors.append(f'{eid}: unknown task {t}')
        if kind == 'sprint-exit':
            m = re.search(r'\bS(\d)\b', task_cell + ' ' + event)
            if m:
                exits.add(int(m.group(1)))
    if not rows:
        errors.append('ledger has no rows')

    integration = state.get('integration_branch', 'v0.2/product-loops')
    for t in tasks:
        tid, status = t.get('id'), t.get('status')
        if status not in STATUSES:
            errors.append(f'{tid}: invalid status {status}')
            continue
        if plan_lane.get(tid) and t.get('lane') != plan_lane[tid]:
            errors.append(f'{tid}: lane {t.get("lane")} differs from plan lane {plan_lane[tid]}')
        if status != 'pending' and not t.get('owner'):
            errors.append(f'{tid}: {status} needs an owner')
        if status == 'in_progress' and not t.get('branch'):
            errors.append(f'{tid}: in_progress needs a branch')
        if level(status) >= level('author_complete') and not t.get('commits'):
            errors.append(f'{tid}: {status} needs at least one commit')
        if level(status) >= level('integrated'):
            for sha in t.get('commits', []):
                if is_ancestor(sha, integration) is False:
                    errors.append(f'{tid}: commit {sha} is not on {integration}')
        sprint = int(tid[1])
        if sprint > 0 and level(status) > level('author_complete') and (sprint - 1) not in exits:
            errors.append(f'{tid}: beyond author_complete before a sprint-exit row for S{sprint-1}')
    return errors


def render(state: dict) -> str:
    out = ['# v0.2 TODO', '',
           'Generated by `execution/v0.2/render_todo.py` from [state.json](state.json). Do not edit by hand.',
           f'Current sprint: {state.get("current_sprint")}. Ledger: [ledger.md](ledger.md).', '']
    counts: dict[str, int] = {}
    for t in state['tasks']:
        counts[t['status']] = counts.get(t['status'], 0) + 1
    out.append('Status: ' + ', '.join(f'{k} {counts[k]}' for k in LEVELS + ['blocked'] if k in counts) + '.')
    for sprint in sorted({t['sprint'] for t in state['tasks']}):
        out += ['', f'## {sprint}', '', '| ID | Lane | Task | Status | Owner | Branch | Commits |', '|---|---|---|---|---|---|---|']
        for t in (t for t in state['tasks'] if t['sprint'] == sprint):
            mark = 'x' if level(t['status']) >= level('integrated') else ' '
            commits = ', '.join(f'`{c[:9]}`' for c in t.get('commits', [])) or '—'
            title = t['title'].replace('|', '\\|')
            out.append(f'| [{mark}] {t["id"]} | {t["lane"]} | {title} | {t["status"]} | {t.get("owner") or "—"} | {t.get("branch") or "—"} | {commits} |')
    blocked = state.get('blocked', [])
    if blocked:
        out += ['', '## Blocked', ''] + [f'- {b["what"]}: {b["needs"]}' for b in blocked]
    return '\n'.join(out) + '\n'


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if TODO.md is stale or rules are violated')
    args = parser.parse_args()
    state = json.loads(STATE.read_text())
    errors = inspect(state, PLAN.read_text(), LEDGER.read_text())
    text = render(state)
    if args.check:
        if not TODO.exists() or TODO.read_text() != text:
            errors.append('TODO.md is stale; run execution/v0.2/render_todo.py')
    elif not errors:
        TODO.write_text(text)
    for e in errors:
        print(f'FAIL: {e}', file=sys.stderr)
    if errors:
        return 1
    print('PASS: v0.2 state, ledger and TODO consistent; product execution remains pending.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
