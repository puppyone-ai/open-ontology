\set ON_ERROR_STOP on
\getenv oo_reader_pw OO_READER_PW
\getenv oo_guc_pw OO_GUC_PW
\getenv oo_alias_pw OO_ALIAS_PW
CREATE ROLE oo_a110_reader LOGIN PASSWORD :'oo_reader_pw' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE oo_a110_guc LOGIN PASSWORD :'oo_guc_pw' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE oo_a110_other NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
CREATE ROLE oo_a110_alias LOGIN PASSWORD :'oo_alias_pw' NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
GRANT oo_a110_other TO oo_a110_alias;
ALTER ROLE oo_a110_guc SET work_mem = '8MB';
ALTER ROLE oo_a110_alias SET role = 'oo_a110_other';
CREATE DATABASE typedb OWNER postgres;
REVOKE ALL ON DATABASE typedb FROM PUBLIC;
GRANT CONNECT ON DATABASE typedb TO oo_a110_reader, oo_a110_guc, oo_a110_alias;
