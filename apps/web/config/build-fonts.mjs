import { createHash } from "node:crypto";
import { createRequire } from "node:module";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const subsetFont = require("subset-font");
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = process.env.FONT_SRC;
if (!srcDir) throw new Error("FONT_SRC is required");

const copy = JSON.parse(await readFile(join(root, "design/copy.json"), "utf8"));
const rare = String(copy.rareGlyph);
const subsetText = Object.entries(copy)
  .filter(([key]) => key !== "rareGlyph")
  .map(([, value]) => String(value))
  .join("")
  .replaceAll(rare, "");
const subsetPoints = [...new Set([...subsetText].map((char) => char.codePointAt(0) ?? 0).filter((point) => point > 127))].sort(
  (left, right) => left - right,
);
if (subsetPoints.includes(rare.codePointAt(0) ?? 0)) {
  throw new Error("rare glyph leaked into the subset");
}

function unicodeRange(points) {
  const parts = [];
  let start = points[0];
  let previous = points[0];
  for (let index = 1; index <= points.length; index += 1) {
    const current = points[index];
    if (current === previous + 1) {
      previous = current;
      continue;
    }
    const left = start.toString(16).toUpperCase();
    const right = previous.toString(16).toUpperCase();
    parts.push(start === previous ? `U+${left}` : `U+${left}-${right}`);
    start = current;
    previous = current;
  }
  return parts.join(", ");
}

const range = unicodeRange(subsetPoints);
const outDir = join(root, "public/fonts");
await mkdir(join(outDir, "licenses"), { recursive: true });
const files = [];

async function emit(name, buffer) {
  await writeFile(join(outDir, name), buffer);
  files.push({
    file: `public/fonts/${name}`,
    bytes: buffer.length,
    sha256: createHash("sha256").update(buffer).digest("hex"),
  });
}

const notoSrc = await readFile(join(srcDir, "NotoSansSC-wght.ttf"));
for (const weight of [300, 400, 500]) {
  const subset = await subsetFont(notoSrc, subsetText, {
    targetFormat: "woff2",
    variationAxes: { wght: weight },
  });
  await emit(`NotoSansSC-${weight}-subset.woff2`, subset);
}
const full = await subsetFont(notoSrc, undefined, {
  keepAllGlyphs: true,
  targetFormat: "woff2",
});
await emit("NotoSansSC-full.woff2", full);
await emit("Geist-wght.woff2", await readFile(join(srcDir, "Geist-wght.woff2")));
await emit("GeistMono-Regular.woff2", await readFile(join(srcDir, "GeistMono-Regular.woff2")));
await writeFile(join(outDir, "licenses/Geist-OFL.txt"), await readFile(join(srcDir, "Geist-OFL.txt")));
await writeFile(join(outDir, "licenses/NotoSans-LICENSE"), await readFile(join(srcDir, "NotoSans-LICENSE")));

const face = (family, file, weight, extra = "") => `@font-face {
  font-family: ${family};
  src: url("/fonts/${file}") format("woff2");
  font-weight: ${weight};
  font-style: normal;
  font-display: swap;
  ${extra}
}`;
const css = `/* Generated by config/build-fonts.mjs. Local files only. */
${face("Geist", "Geist-wght.woff2", "100 900")}
${face('"Geist Mono"', "GeistMono-Regular.woff2", "400")}
${face('"Noto Sans SC"', "NotoSansSC-300-subset.woff2", "300", `unicode-range: ${range};`)}
${face('"Noto Sans SC"', "NotoSansSC-400-subset.woff2", "400", `unicode-range: ${range};`)}
${face('"Noto Sans SC"', "NotoSansSC-500-subset.woff2", "500", `unicode-range: ${range};`)}
${face('"Noto Sans SC Full"', "NotoSansSC-full.woff2", "100 900")}
`;
await writeFile(join(root, "src/styles/fonts.css"), css);
const zip = await readFile(join(srcDir, "geist-font-v1.7.2.zip"));
const manifest = {
  notoSource: {
    repository: "notofonts/noto-cjk",
    path: "google-fonts/NotoSansSC[wght].ttf",
    commit: "f8d157532fbfaeda587e826d4cd5b21a49186f7c",
    blob: "1082735610a1b64f612dc50a211f0f37c1b2ad9d",
    bytes: notoSrc.length,
    sha256: createHash("sha256").update(notoSrc).digest("hex"),
  },
  geistSource: {
    release: "https://github.com/vercel/geist-font/releases/download/v1.7.2/geist-font-v1.7.2.zip",
    bytes: zip.length,
    sha256: createHash("sha256").update(zip).digest("hex"),
  },
  subsetCodepoints: subsetPoints,
  unicodeRange: range,
  rareGlyph: rare,
  files,
};
await writeFile(join(root, "design/font-manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
console.log(`subsetPoints=${subsetPoints.length} fullBytes=${full.length}`);
