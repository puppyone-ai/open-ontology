// Generates THIRD_PARTY_NOTICES.md (committed) and the legal folder of the package (build/generated/legal, ignored):
// NOTICE, LICENSE, THIRD_PARTY_NOTICES.md and release.json. `--check` fails when the committed THIRD_PARTY_NOTICES.md is stale.
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");

// `pnpm licenses --prod` lists what an importer needs, but not the packages its workspace dependency needs: the design system's own
// runtime packages (intl-messageformat and its formatjs parts) are bundled into the renderer too, so that importer is read as well.
const IMPORTERS = [root, path.resolve(root, "../../packages/design-system")];

function productionPackages() {
  const merged = new Map();
  for (const cwd of IMPORTERS) {
    let raw;
    try { raw = execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], { cwd, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }); } catch { continue; }
    const trimmed = raw.trim();
    if (!trimmed) continue;
    for (const [license, entries] of Object.entries(JSON.parse(trimmed))) {
      for (const entry of entries) {
        const key = `${entry.name}|${license}`;
        const known = merged.get(key);
        const versions = new Set([...(known?.versions ?? []), ...(entry.versions ?? [])]);
        merged.set(key, { name: entry.name, versions, license, homepage: entry.homepage ?? known?.homepage ?? "" });
      }
    }
  }
  return [...merged.values()].map((row) => ({ ...row, versions: [...row.versions].sort().join(", ") })).sort((a, b) => a.name.localeCompare(b.name));
}

function thirdParty() {
  const rows = productionPackages();
  const lines = [
    "# Third-party notices", "",
    "Generated by `scripts/gen-notice.mjs`; do not edit by hand.", "",
    "## Runtime", "",
    "- Electron, with Chromium and Node.js (MIT and the licenses collected in `LICENSES.chromium.html` inside the Electron Framework of the app bundle).",
    "- `oo` (Resources/oo/oo): built from this repository; see the repository NOTICE and `supply-chain/licenses`.", "",
    "## Packages bundled into the renderer or the main process", "",
  ];
  if (rows.length === 0) lines.push("None: the main process uses Node.js and Electron only.");
  else { lines.push("| Package | Version | License | Home |", "|---|---|---|---|"); for (const row of rows) lines.push(`| ${row.name} | ${row.versions} | ${row.license} | ${row.homepage} |`); }
  return `${lines.join("\n")}\n`;
}

const committed = path.join(root, "THIRD_PARTY_NOTICES.md");
const content = thirdParty();
if (check) {
  if (!fs.existsSync(committed) || fs.readFileSync(committed, "utf8") !== content) { console.error("THIRD_PARTY_NOTICES.md is stale: run gen:notice."); process.exit(1); }
  console.log("THIRD_PARTY_NOTICES.md is current.");
  process.exit(0);
}
fs.writeFileSync(committed, content);

function releaseUrl() {
  const slug = process.env.GITHUB_REPOSITORY;
  if (slug && /^[\w.-]+\/[\w.-]+$/u.test(slug)) return `https://github.com/${slug}/releases`;
  try {
    const remote = execFileSync("git", ["remote", "get-url", "origin"], { cwd: root, encoding: "utf8" }).trim();
    const match = /github\.com[:/]([\w.-]+\/[\w.-]+?)(?:\.git)?$/u.exec(remote);
    return match ? `https://github.com/${match[1]}/releases` : null;
  } catch { return null; }
}

const legal = path.join(root, "build", "generated", "legal");
fs.rmSync(legal, { recursive: true, force: true });
fs.mkdirSync(legal, { recursive: true });
for (const name of ["NOTICE", "LICENSE", "THIRD_PARTY_NOTICES.md"]) fs.copyFileSync(path.join(root, name), path.join(legal, name));
const url = releaseUrl();
fs.writeFileSync(path.join(legal, "release.json"), `${JSON.stringify({ url }, null, 2)}\n`);
console.log(`legal folder written (${url ? "release link set" : "no release link"})`);
