//! Allocation-free kernels of the pack compiler: the parts of D26 (KP5), of
//! the BRIEF ordering and degradation (KP6) and of the AIGC label (KP10) that
//! Kani can prove (80 section 3.2). The compiler calls them; `proofs.rs`
//! proves them. They work on small integers, slices and byte sinks, never on
//! maps or strings that grow.

use std::cmp::Ordering;

use super::render::{AIGC_LABEL_LINE, CONTENT_PRODUCER};

// ---------------------------------------------------------------- KP6: order

/// What BRIEF ranks an entry by (10 7.3 step 4): hit a seed first, newer
/// `valid_from` first (none last), more in-scope evidence first, then entity
/// key and fact key ascending. All comparisons are on bytes.
#[derive(Clone, Copy, Debug)]
pub(crate) struct RankKey<'a> {
    pub seed_hit: bool,
    pub valid_from: Option<&'a str>,
    pub evs: usize,
    pub subject: &'a str,
    pub fact_key: Option<&'a str>,
}

/// The ranking order. A total preorder; two keys compare equal only when every
/// field is equal (KP6).
pub(crate) fn rank_cmp_keys(a: &RankKey<'_>, b: &RankKey<'_>) -> Ordering {
    b.seed_hit
        .cmp(&a.seed_hit)
        .then_with(|| b.valid_from.cmp(&a.valid_from))
        .then_with(|| b.evs.cmp(&a.evs))
        .then_with(|| a.subject.cmp(b.subject))
        .then_with(|| a.fact_key.cmp(&b.fact_key))
}

// ---------------------------------------------------------- KP6: degradation

/// Precision levels of a BRIEF line, as numbers: 0 full, 1 summary, 2 title,
/// 3 removed (10 7.3 step 6, D25).
pub(crate) const REMOVED: u8 = 3;

/// Section numbers in the order degradation visits them (10 7.3 step 6: 6, 5, 4, 2, 3 of the BRIEF
/// table): other, preferences, tried and failed, people, state. `brief.rs` has a test that its own
/// `Sec::DEGRADE_ORDER` is this list.
#[cfg(any(test, kani))]
pub(crate) const DEGRADE_ORDER: [u8; 5] = [4, 3, 2, 0, 1];

/// One step down; `removed` stays removed.
pub(crate) const fn next_level(level: u8) -> u8 {
    if level >= REMOVED { REMOVED } else { level + 1 }
}

/// The entry that loses precision next in section `sec`: the lowest ranked
/// one (the last of the section) that is not yet removed. `get(i)` is the
/// `(section, level)` of entry `i`.
pub(crate) fn lowest_degradable_by(
    n: usize,
    get: impl Fn(usize) -> (u8, u8),
    sec: u8,
) -> Option<usize> {
    let mut i = n;
    while i > 0 {
        i -= 1;
        let (s, l) = get(i);
        if s == sec && l != REMOVED {
            return Some(i);
        }
    }
    None
}

// -------------------------------------------------------------- KP5: D26

/// The decision of D26 on indices (10 7.2). A fact is visible iff it has at
/// least one evidence in scope and both of its ends are known entities; an
/// alias iff it has evidence in scope and its owner is a known entity; an
/// entity iff a visible fact or a visible alias points at it. Nothing here
/// reads a name or a text.
///
/// `fact_subject`, `fact_object` and `alias_owner` index the entity slots
/// (`entity_known` tells which slot holds a real entity).
#[allow(clippy::too_many_arguments)]
pub(crate) fn visible_decide(
    fact_has_scoped_ev: &[bool],
    fact_subject: &[usize],
    fact_object: &[Option<usize>],
    alias_has_scoped_ev: &[bool],
    alias_owner: &[usize],
    entity_known: &[bool],
    fact_visible: &mut [bool],
    alias_visible: &mut [bool],
    entity_visible: &mut [bool],
) {
    let known = |e: usize| e < entity_known.len() && entity_known[e];
    for e in entity_visible.iter_mut() {
        *e = false;
    }
    for i in 0..fact_visible.len() {
        let ends_ok = known(fact_subject[i]) && fact_object[i].is_none_or(known);
        fact_visible[i] = fact_has_scoped_ev[i] && ends_ok;
        if fact_visible[i] {
            entity_visible[fact_subject[i]] = true;
            if let Some(o) = fact_object[i] {
                entity_visible[o] = true;
            }
        }
    }
    for i in 0..alias_visible.len() {
        alias_visible[i] = alias_has_scoped_ev[i] && known(alias_owner[i]);
        if alias_visible[i] {
            entity_visible[alias_owner[i]] = true;
        }
    }
}

// ---------------------------------------------------------- KP10: AIGC label

/// Where generated bytes go. `Vec<u8>` in the compiler, a fixed buffer in the
/// proofs.
pub(crate) trait Sink {
    fn put(&mut self, bytes: &[u8]);
    /// Remove the last byte.
    fn pop(&mut self);
    fn tail_is_blank_line(&self) -> bool;
}

impl Sink for Vec<u8> {
    fn put(&mut self, bytes: &[u8]) {
        self.extend_from_slice(bytes);
    }
    fn pop(&mut self) {
        Vec::pop(self);
    }
    fn tail_is_blank_line(&self) -> bool {
        self.ends_with(b"\n\n")
    }
}

/// `---` YAML block with the `AIGC` metadata (D66): a function of `basis` and
/// `path` only, no clock, no random value.
pub(crate) fn put_front_matter(out: &mut impl Sink, basis: &[u8], path: &[u8]) {
    out.put(b"---\nAIGC:\n  Label: \"1\"\n  ContentProducer: \"");
    out.put(CONTENT_PRODUCER.as_bytes());
    out.put(b"\"\n  ProduceID: \"");
    out.put(basis);
    out.put(b"/");
    out.put(path);
    out.put(b"\"\n  ReservedCode1: \"");
    out.put(basis);
    out.put(b"\"\n  ContentPropagator: \"\"\n  PropagateID: \"\"\n  ReservedCode2: \"\"\n---\n");
}

/// Label line, blank line, front matter, blank line: everything before the
/// body of a generated Markdown file.
pub(crate) fn put_md_prefix(out: &mut impl Sink, basis: &[u8], path: &[u8]) {
    out.put(AIGC_LABEL_LINE.as_bytes());
    out.put(b"\n\n");
    put_front_matter(out, basis, path);
    out.put(b"\n");
}

/// A whole generated Markdown file: the prefix, the body lines each followed
/// by `\n`, trailing blank lines cut down to the single final `\n`.
pub(crate) fn put_md_file<'a>(
    out: &mut impl Sink,
    basis: &[u8],
    path: &[u8],
    body: impl Iterator<Item = &'a [u8]>,
) {
    put_md_prefix(out, basis, path);
    for line in body {
        out.put(line);
        out.put(b"\n");
    }
    while out.tail_is_blank_line() {
        out.pop();
    }
}
